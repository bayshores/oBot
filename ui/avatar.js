  /** Flatten an SVG path (M, L, Q, C, Z; absolute) into points, segments at most `step` long. */
  function flattenPath(d, step = 4) {
    const tok = d.match(/[MLCQZmlcqz]|-?\d*\.?\d+(?:e[-+]?\d+)?/g) || [];
    const out = [];
    let i = 0, cmd = '', x = 0, y = 0, sx = 0, sy = 0;
    const num = () => parseFloat(tok[i++]);
    const emit = (f, len) => {
      const n = Math.max(2, Math.ceil(len / step));
      for (let k = 1; k <= n; k++) out.push(f(k / n));
    };
    while (i < tok.length) {
      if (/[a-z]/i.test(tok[i])) cmd = tok[i++].toUpperCase();
      if (cmd === 'Z') {
        const len = Math.hypot(sx - x, sy - y);
        if (len > 0.01) { const x0 = x, y0 = y; emit((t) => [x0 + (sx - x0) * t, y0 + (sy - y0) * t], len); }
        x = sx; y = sy;
        continue;
      }
      if (i >= tok.length) break;
      if (cmd === 'M') {
        x = num(); y = num(); sx = x; sy = y; out.push([x, y]); cmd = 'L';
      } else if (cmd === 'L') {
        const nx = num(), ny = num(), x0 = x, y0 = y;
        emit((t) => [x0 + (nx - x0) * t, y0 + (ny - y0) * t], Math.hypot(nx - x0, ny - y0));
        x = nx; y = ny;
      } else if (cmd === 'Q') {
        const cx = num(), cy = num(), nx = num(), ny = num(), x0 = x, y0 = y;
        emit((t) => {
          const m = 1 - t;
          return [m * m * x0 + 2 * m * t * cx + t * t * nx, m * m * y0 + 2 * m * t * cy + t * t * ny];
        }, Math.hypot(cx - x0, cy - y0) + Math.hypot(nx - cx, ny - cy));
        x = nx; y = ny;
      } else {
        const c1x = num(), c1y = num(), c2x = num(), c2y = num(), nx = num(), ny = num(), x0 = x, y0 = y;
        emit((t) => {
          const m = 1 - t;
          return [
            m * m * m * x0 + 3 * m * m * t * c1x + 3 * m * t * t * c2x + t * t * t * nx,
            m * m * m * y0 + 3 * m * m * t * c1y + 3 * m * t * t * c2y + t * t * t * ny,
          ];
        }, Math.hypot(c1x - x0, c1y - y0) + Math.hypot(c2x - c1x, c2y - c1y) + Math.hypot(nx - c2x, ny - c2y));
        x = nx; y = ny;
      }
    }
    return out;
  }

  /** Scanline table: outline y extent and the inner left/right x at any height. */
  function scanTable(pts, rows = 160) {
    let top = Infinity, bottom = -Infinity;
    for (const p of pts) { if (p[1] < top) top = p[1]; if (p[1] > bottom) bottom = p[1]; }
    const h = bottom - top;
    const rowY = (r) => top + (h * (r + 0.5)) / rows;
    const inL = new Float64Array(rows), inR = new Float64Array(rows);
    const outL = new Float64Array(rows), outR = new Float64Array(rows);
    for (let r = 0; r < rows; r++) {
      const y = rowY(r);
      let a = -Infinity, b = Infinity, lo = Infinity, hi = -Infinity;
      for (let k = 0; k < pts.length; k++) {
        const p = pts[k], q = pts[(k + 1) % pts.length];
        if ((p[1] <= y) === (q[1] <= y)) continue;
        const x = p[0] + ((q[0] - p[0]) * (y - p[1])) / (q[1] - p[1]);
        if (x <= L) { if (x > a) a = x; } else if (x < b) b = x;
        if (x < lo) lo = x;
        if (x > hi) hi = x;
      }
      inL[r] = Number.isFinite(a) ? a : L; inR[r] = Number.isFinite(b) ? b : L;
      outL[r] = Number.isFinite(lo) ? lo : L; outR[r] = Number.isFinite(hi) ? hi : L;
    }
    const sampler = (A, B) => (y) => {
      const f = clamp(((y - top) / h) * rows - 0.5, 0, rows - 1);
      const r0 = Math.floor(f), t = f - r0, r1 = Math.min(r0 + 1, rows - 1);
      return [A[r0] + (A[r1] - A[r0]) * t, B[r0] + (B[r1] - B[r0]) * t];
    };
    return { top, bottom, spanAt: sampler(inL, inR), outerAt: sampler(outL, outR) };
  }

  /** 96 points on the outline: the farthest crossing along rays from the box centre. */
  function rayRing(pts, count = 96) {
    return Array.from({ length: count }, (_, n) => {
      const th = (n / count) * TAU, c = Math.cos(th), s = Math.sin(th);
      let reach = 0;
      for (let k = 0; k < pts.length; k++) {
        const p = pts[k], q = pts[(k + 1) % pts.length];
        const ax = p[0] - L, ay = p[1] - L, bx = q[0] - L, by = q[1] - L;
        const den = (bx - ax) * s - (by - ay) * c;
        if (Math.abs(den) < 1e-9) continue;
        const u = (ax * s - ay * c) / -den;
        if (u < 0 || u > 1) continue;
        const dist = (ax + (bx - ax) * u) * c + (ay + (by - ay) * u) * s;
        if (dist > reach) reach = dist;
      }
      return [L + c * reach, L + s * reach];
    });
  }

  /** Centre an outline and scale it so its long side is about 228.44. */
  function normalizeOutline(d) {
    const pts = flattenPath(d);
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    for (const [x, y] of pts) {
      if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
    }
    const k = clamp(228.44 / Math.max(x1 - x0, y1 - y0), 0.9, 1.35);
    const dx = L - (x0 + x1) / 2, dy = L - (y0 + y1) / 2;
    if (Math.abs(k - 1) < 0.005 && Math.abs(dx) < 0.5 && Math.abs(dy) < 0.5) return d;
    let isX = false;
    return d.replace(/-?\d*\.?\d+(?:e[-+]?\d+)?/gi, (m) => {
      isX = !isX;
      const v = parseFloat(m) + (isX ? dx : dy);
      return String(round2(L + (v - L) * k));
    });
  }

  function outlineInfo(rawPath) {
    const path = normalizeOutline(rawPath);
    const pts = flattenPath(path);
    const scan = scanTable(pts);
    let belt = 0;
    for (let y = scan.top; y <= scan.bottom; y += 2) {
      const [a, b] = scan.outerAt(y);
      belt = Math.max(belt, (b - a) / 2);
    }
    return { path, ring: rayRing(pts), top: round2(scan.top), bottom: round2(scan.bottom), spanAt: scan.spanAt, beltRadius: round2(belt) };
  }

