  /** Close a stroke into a loop: offset the centre line both ways, round caps of 10 steps. */
  function strokeLoop(centre, nx, ny, r, startDir, endDir) {
    const n = centre.length;
    const left = centre.map((p, i) => ({ x: p.x + nx[i] * r, y: p.y + ny[i] * r }));
    const right = centre.map((p, i) => ({ x: p.x - nx[i] * r, y: p.y - ny[i] * r }));
    const cap = (c, from, to) => {
      const out = [], a0 = Math.atan2(from.y - c.y, from.x - c.x);
      let sweep = Math.atan2(to.y - c.y, to.x - c.x) - a0;
      while (sweep > Math.PI) sweep -= TAU;
      while (sweep < -Math.PI) sweep += TAU;
      const dir = sweep >= 0 ? 1 : -1;
      for (let i = 1; i < 10; i++) {
        const a = a0 + (i / 10) * dir * Math.PI;
        out.push({ x: c.x + r * Math.cos(a), y: c.y + r * Math.sin(a) });
      }
      return out;
    };
    const tipEnd = { x: centre[n - 1].x + endDir.x * r, y: centre[n - 1].y + endDir.y * r };
    const tipStart = { x: centre[0].x - startDir.x * r, y: centre[0].y - startDir.y * r };
    const endCap = cap(centre[n - 1], left[n - 1], tipEnd);
    const startCap = cap(centre[0], right[0], tipStart);
    return [...left, ...endCap, ...right.reverse(), ...startCap];
  }

  /** A short, fat stroke is drawn as its 48-direction support hull instead. */
  function fatStrokeHull(pts, r) {
    let cx = 0, cy = 0;
    for (const p of pts) { cx += p.x; cy += p.y; }
    cx /= pts.length; cy /= pts.length;
    let spread = 0;
    for (const p of pts) spread = Math.max(spread, Math.hypot(p.x - cx, p.y - cy));
    if (r <= spread * 1.05) return null;
    const out = [];
    for (let i = 0; i < 48; i++) {
      const a = (i / 48) * TAU, c = Math.cos(a), s = Math.sin(a);
      let best = -Infinity, bx = 0, by = 0;
      for (const p of pts) { const d = p.x * c + p.y * s; if (d > best) { best = d; bx = p.x; by = p.y; } }
      out.push({ x: bx + c * r, y: by + s * r });
    }
    return out;
  }

  const unitVec = (x, y) => { const l = Math.hypot(x, y) || 1; return { x: x / l, y: y / l }; };

  /** Stroke outline from the Bezier path (11 samples per segment), mapped through `place`. */
  function strokeFromPath(path, place, r) {
    if (r <= 0) return [];
    const pts = [];
    for (let seg = 0; seg < 2; seg++) {
      const a = pathAnchor(path, seg), b = pathHandle(path, seg, true), c = pathHandle(path, seg + 1, false), d = pathAnchor(path, seg + 1);
      for (let k = seg === 0 ? 0 : 1; k < 11; k++) {
        const t = k / 10, p = cubicAt(a, b, c, d, t), tan = cubicTangent(a, b, c, d, t);
        const q = place(p[0], p[1]), q2 = place(p[0] + tan[0], p[1] + tan[1]);
        pts.push({ x: q.x, y: q.y, tx: q2.x - q.x, ty: q2.y - q.y });
      }
    }
    const fat = fatStrokeHull(pts, r);
    if (fat) return fat;
    const nx = [], ny = [];
    for (let i = 0; i < pts.length; i++) {
      const len = Math.hypot(pts[i].tx, pts[i].ty) || 1;
      let x = -pts[i].ty / len, y = pts[i].tx / len;
      if (i > 0 && x * nx[i - 1] + y * ny[i - 1] < 0) { x = -x; y = -y; }
      nx.push(x); ny.push(y);
    }
    const first = pts[0], last = pts[pts.length - 1];
    return strokeLoop(pts, nx, ny, r, unitVec(first.tx, first.ty), unitVec(last.tx, last.ty));
  }

  /** Stroke outline from plain centre-line points. */
  function strokeFromPoints(points, r) {
    const pts = [];
    for (const p of points) {
      const last = pts[pts.length - 1];
      if (last == null || Math.hypot(p.x - last.x, p.y - last.y) > 1e-6) pts.push(p);
    }
    if (pts.length === 0 || r <= 0) return [];
    const fat = fatStrokeHull(pts, r);
    if (fat) return fat;
    const n = pts.length;
    if (n < 2) return [];
    const nx = [], ny = [];
    for (let i = 0; i < n; i++) {
      const a = pts[Math.max(0, i - 1)], b = pts[Math.min(n - 1, i + 1)];
      const len = Math.hypot(b.x - a.x, b.y - a.y) || 1;
      let x = -(b.y - a.y) / len, y = (b.x - a.x) / len;
      if (i > 0 && x * nx[i - 1] + y * ny[i - 1] < 0) { x = -x; y = -y; }
      nx.push(x); ny.push(y);
    }
    return strokeLoop(pts, nx, ny, r, unitVec(pts[1].x - pts[0].x, pts[1].y - pts[0].y), unitVec(pts[n - 1].x - pts[n - 2].x, pts[n - 1].y - pts[n - 2].y));
  }

  /**
   * 2D eye loops on the face (model units, y up), before they are put on the body.
   * scale: eye size factor; gapK: centre distance factor; heightK: vertical offset factor.
   */
  function faceLoops(pair, scale, gapK, heightK, shiftX, shiftY) {
    const loops = [], sx = Math.sin(shiftX), base = -Math.sin(shiftY);
    pair.forEach((e, i) => {
      const oval = isOval(e);
      if ((!(e.wid > 0) && !oval) || (!oval && e.pts.length < 2)) return;
      const side = i === 0 ? -1 : 1, lid = e.lidY || 1;
      const c = Math.cos(e.tilt || 0), s = Math.sin(e.tilt || 0);
      const cx = side * ((EYE_GAP / 2 + finite(e.off[0])) * gapK) + sx;
      const cy = base + finite(e.off[1]) * heightK;
      const place = (px, py) => {
        const rx = px * c - py * s, ry = px * s + py * c;
        return { x: cx + side * rx * scale, y: cy + ry * scale * lid };
      };
      if (e.fillRing != null && e.fillRing.length >= 3) {
        const ox = finite(e.off[0]), oy = finite(e.off[1]);
        loops.push(e.fillRing.map(([x, y]) => place(x - ox, (y - oy) * lid)));
        return;
      }
      if (oval) {
        const ring = [];
        for (let k = 0; k < 48; k++) {
          const a = (k / 48) * TAU;
          ring.push(place(e.oval[0] * Math.cos(a), e.oval[1] * lid * Math.sin(a)));
        }
        loops.push(ring);
        return;
      }
      const r = e.wid * scale;
      const loop = e.path != null && e.path.length === 18 ? strokeFromPath(e.path, place, r) : strokeFromPoints(e.pts.map((p) => place(p[0], p[1])), r);
      if (loop.length > 0) loops.push(loop);
    });
    return loops;
  }

  /** Simple description of an eye for the "both eyes are ovals" layout. */
  function ovalSummary(e) {
    const oval = isOval(e);
    if (!(e.wid > 0) && !oval) return { on: false, width: 0, height: 0, tilt: 0, cx: 0, cy: 0 };
    const lid = e.lidY || 1, tilt = (e.tilt || 0) / DEG;
    if (oval) return { on: true, width: 2 * e.oval[0], height: 2 * e.oval[1] * lid, tilt, cx: e.off[0], cy: e.off[1] };
    if (e.pts.length < 2) return { on: false, width: 0, height: 0, tilt: 0, cx: e.off[0], cy: e.off[1] };
    const a = e.pts[0], b = e.pts[e.pts.length - 1], dx = b[0] - a[0], dy = b[1] - a[1], w = 2 * e.wid;
    return {
      on: true, width: w, height: (Math.hypot(dx, dy) + w) * lid, tilt: Math.atan2(dx, dy) / DEG + tilt,
      cx: e.off[0] + (a[0] + b[0]) / 2, cy: e.off[1] + ((a[1] + b[1]) / 2) * lid,
    };
  }

  function ellipseLoop(side, minor, major, tiltDeg, gap) {
    const a = Math.max(0.01, Math.min(1, minor)) / 2, b = Math.max(0.02, Math.min(1.8, Math.max(major, minor))) / 2;
    const t = -tiltDeg * DEG, c = Math.cos(t), s = Math.sin(t);
    return Array.from({ length: 64 }, (_, i) => {
      const ang = (2 * Math.PI * i) / 64, x = side * b * Math.cos(ang), y = a * Math.sin(ang);
      return { x: x * c - y * s + (side * gap) / 2, y: x * s + y * c };
    });
  }

  /** Eye loops + vertical shift for a table shape. */
  function shapeFace(body, pair) {
    const [width, height, gap, shiftY] = FACE_LAYOUT[body];
    const s = width / EYE_WIDTH, v = height / EYE_HEIGHT, g = gap / EYE_GAP;
    if (pair.every((e) => isOval(e) && !(e.fillRing != null && e.fillRing.length > 0))) {
      const a = ovalSummary(pair[0]), b = ovalSummary(pair[1]);
      const aw = finite(a.width * s), ah = finite(a.height * s), bw = finite(b.width * s), bh = finite(b.height * s);
      const centres = Math.max(0, finite((EYE_GAP + (a.on ? finite(a.cx) : 0) + (b.on ? finite(b.cx) : 0)) * g, EYE_GAP * g));
      const h = Math.max(0.05, Math.min(1.8, centres));
      return {
        loops: [
          ellipseLoop(-1, Math.max(0, finite(Math.min(aw, ah))), Math.max(0, finite(Math.max(aw, ah))), -finite(finite(a.tilt) + (aw >= ah ? 0 : 90)), h),
          ellipseLoop(1, Math.max(0, finite(Math.min(bw, bh))), Math.max(0, finite(Math.max(bw, bh))), finite(finite(b.tilt) + (bw >= bh ? 0 : 90)), h),
        ],
        shiftY: finite(shiftY + ((finite(a.cy) + finite(b.cy)) / 2) * v, shiftY),
      };
    }
    return { loops: faceLoops(pair, s, g, v, 0, shiftY), shiftY: 0 };
  }

  /** Map 2D eye loops onto the body surface and project them. */
  function seatEyes(seat, face, view) {
    switch (seat.kind) {
      case 'front': return seatFront(seat.faceZ, face, view);
      case 'loft': return seatLoft(seat.surfaceZ, face, view);
      case 'wrap': return seatWrap(seat, face, view);
      case 'wrapX': return seatWrapX(seat, face, view);
      default: return [];
    }
  }

  function seatFront(faceZ, { loops, shiftY }, view) {
    if (!(view.rotate({ x: 0, y: 0, z: 1 }).z > 0.03)) return [];
    const dy = Math.sin(shiftY);
    return loops.filter((l) => l.length >= 3).map((l) => l.map((p) => view.project({ x: p.x, y: p.y - dy, z: faceZ })));
  }

  function seatLoft(surfaceZ, { loops, shiftY }, { rotate, project }) {
    if (!(rotate({ x: 0, y: 0, z: 1 }).z >= 0.05)) return [];
    const dy = Math.sin(shiftY), out = [];
    for (const l of loops) {
      if (l.length < 3) continue;
      const pts = l.map((p) => ({ x: p.x, y: p.y - dy }));
      let cx = 0, cy = 0;
      for (const p of pts) { cx += p.x; cy += p.y; }
      cx /= pts.length; cy /= pts.length;
      const h = 0.004;
      const gx = (surfaceZ(cx + h, cy) - surfaceZ(cx - h, cy)) / (2 * h);
      const gy = (surfaceZ(cx, cy + h) - surfaceZ(cx, cy - h)) / (2 * h);
      const n = Math.hypot(gx, gy, 1);
      if (rotate({ x: -gx / n, y: -gy / n, z: 1 / n }).z < 0.12) continue;
      const z0 = surfaceZ(cx, cy);
      out.push(pts.map((p) => project({ x: p.x, y: p.y, z: z0 + (p.x - cx) * gx + (p.y - cy) * gy })));
    }
    return out;
  }

  function seatWrap(seat, { loops, shiftY }, { rotate, project }) {
    const { wrapR, wrapY0: y0, wrapY1: y1, radiusAt, puffAt } = seat;
    const margin = radiusAt ? 0.02 : 0.06;
    const d = Math.min(y1 - margin, Math.max(y0 + margin, seat.eyeY - shiftY));
    const clampY = (y) => Math.min(y1, Math.max(y0, y));
    const onRevolve = (loop) => {
      const out = [];
      for (const p of loop) {
        const y = clampY(d + p.y), r = radiusAt ? radiusAt(y) : wrapR;
        const u = Math.max(-2.6, Math.min(2.6, p.x / Math.max(0.12, r)));
        let slope = 0;
        if (radiusAt) { const h = 0.012; slope = -(radiusAt(Math.min(y1, y + h)) - radiusAt(Math.max(y0, y - h))) / (2 * h); }
        if (rotate({ x: Math.sin(u), y: slope, z: Math.cos(u) }).z >= 0.05) out.push(project({ x: r * Math.sin(u), y, z: r * Math.cos(u) }));
      }
      return out;
    };
    const onBalls = (loop) => {
      if (!puffAt || loop.length === 0) return [];
      let sx = 0, sy = 0;
      for (const p of loop) { sx += p.x; sy += p.y; }
      const ball = puffAt(sx / loop.length, clampY(d + sy / loop.length));
      const front = rotate({ x: 0, y: 0, z: 1 }).z, out = [];
      for (const p of loop) {
        const dx = p.x - ball.x, dy = clampY(d + p.y) - ball.y, dist = Math.hypot(dx, dy);
        let ang = Math.min(dist / ball.r, Math.PI - 0.02);
        const ux = dist > 1e-9 ? dx / dist : 1, uy = dist > 1e-9 ? dy / dist : 0;
        const side = rotate({ x: ux, y: uy, z: 0 }).z;
        const facing = (a) => side * Math.sin(a) + front * Math.cos(a);
        if (facing(ang) < 0.06 && front > 0.06) {
          let lo = 0, hi = ang;
          for (let k = 0; k < 20; k++) { const mid = (lo + hi) / 2; if (facing(mid) >= 0.06) lo = mid; else hi = mid; }
          ang = lo;
        }
        const ring = ball.r * Math.sin(ang);
        if (rotate({ x: ux * Math.sin(ang), y: uy * Math.sin(ang), z: Math.cos(ang) }).z >= 0.05) {
          out.push(project({ x: ball.x + ux * ring, y: ball.y + uy * ring, z: ball.z + ball.r * Math.cos(ang) }));
        }
      }
      return out;
    };
    let lo = Infinity, hi = -Infinity;
    for (const l of loops) for (const p of l) { if (p.y < lo) lo = p.y; if (p.y > hi) hi = p.y; }
    let push = 0;
    if (hi - lo <= y1 - y0) { if (d + lo < y0) push = y0 - (d + lo); else if (d + hi > y1) push = y1 - (d + hi); }
    const moved = push === 0 ? loops : loops.map((l) => l.map((p) => ({ x: p.x, y: p.y + push })));
    return moved.map(puffAt ? onBalls : onRevolve).filter((l) => l.length > 2);
  }

  function seatWrapX(seat, { loops, shiftY }, { rotate, project }) {
    const { wrapR: a, wrapX0: x0, wrapX1: x1, radiusAtX } = seat;
    const base = Math.max(-2.4, Math.min(2.4, -shiftY / a));
    let lo = Infinity, hi = -Infinity;
    for (const l of loops) for (const p of l) { if (p.x < lo) lo = p.x; if (p.x > hi) hi = p.x; }
    let push = 0;
    if (hi - lo <= x1 - x0) { if (lo < x0) push = x0 - lo; else if (hi > x1) push = x1 - hi; }
    const moved = push === 0 ? loops : loops.map((l) => l.map((p) => ({ x: p.x + push, y: p.y })));
    return moved.map((l) => {
      const out = [];
      for (const p of l) {
        const x = Math.min(x1, Math.max(x0, p.x)), r = radiusAtX(x);
        const ang = base + Math.max(-2.6, Math.min(2.6, p.y / Math.max(0.12, a)));
        const h = 0.012;
        const slope = -(radiusAtX(Math.min(x1, x + h)) - radiusAtX(Math.max(x0, x - h))) / (2 * h);
        if (rotate({ x: slope, y: Math.sin(ang), z: Math.cos(ang) }).z >= 0.05) out.push(project({ x, y: r * Math.sin(ang), z: r * Math.cos(ang) }));
      }
      return out;
    }).filter((l) => l.length > 2);
  }

