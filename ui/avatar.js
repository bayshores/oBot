  function bezierEase(t, ease) {
    const [x1, y1, x2, y2] = ease;
    const bx = (u) => { const m = 1 - u; return 3 * m * m * u * x1 + 3 * m * u * u * x2 + u * u * u; };
    const dx = (u) => { const m = 1 - u; return 3 * m * m * x1 + 6 * m * u * (x2 - x1) + 3 * u * u * (1 - x2); };
    let u = t;
    for (let i = 0; i < 8; i++) {
      const err = bx(u) - t;
      const d = dx(u);
      if (Math.abs(err) < 1e-6 || Math.abs(d) < 1e-6) break;
      u = clamp(u - err / d, 0, 1);
    }
    const m = 1 - u;
    return 3 * m * m * u * y1 + 3 * m * u * u * y2 + u * u * u;
  }

