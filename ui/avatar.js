  // 12. The animator: plays clips and mixes in gaze, pokes, face and morphs
  // ===========================================================================

  function createAnimator(initialBody) {
    const face = createFace();
    const morph = createMorphDriver();
    let body = initialBody;
    let fromBodies = [];                 // bodies being morphed away from
    const bodyBlend = spring(1);
    let spinBase = null;                 // rotation the morph spins around
    let rot = REST_POSE, pos = [0, 0], scl = [1, 1], anchor = 0, zoom = REST_ZOOM;
    let inspect = { bias: -1, isFollowingTurn: true };
    let look = null;
    let gaze = { isHeld: false, isAlways: false, x: 0, y: 0, cx: 0, cy: 0, hold: 0 };
    let cur = REST_CLIP, time = 0, playing = false, looping = true, paused = false;
    let loaded = null, pending = null, loops = 0, heldFace = null, deferred = null, lidsLocked = false;
    let pokes = [];

    const applyPose = () => {
      const p = sampleTrack(cur.position, time); pos = p ? [p[0], p[1]] : [0, 0];
      const r = sampleTrack(cur.rotation, time); rot = r ? [r[0], r[1], r[2]] : [0, 0, 0];
      const s = sampleTrack(cur.squash, time); scl = s ? [s[0], s[1]] : [1, 1];
      const z = sampleTrack(cur.zoom, time); if (z) zoom = clamp(z[0], 0.25, 2.5);
    };
    const clipLids = () => { const v = sampleTrack(cur.lids, time); return v ? clamp(v[0], 0, 1) : 0; };
    const lids = () => (lidsLocked ? 0 : clipLids());
    const updateLidLock = () => {
      if (!canBlink(face.name) || face.isMorphing) lidsLocked = true; else if (lidsLocked && clipLids() === 0) lidsLocked = false;
    };
    /** Run `fn` now, or as soon as the eyes are open again. */
    const whenEyesOpen = (fn) => {
      if ((face.blinkAmount() ?? lids()) > 0) deferred = fn; else { fn(); updateLidLock(); }
    };
    const fireExpressions = (t0, t1) => {
      if (heldFace != null) return;
      for (const k of cur.expression) if (k.t > t0 && k.t <= t1) whenEyesOpen(() => face.play(k));
    };
    const seek = (t) => {
      time = t; look = null; deferred = null; applyPose();
      face.seek(cur.expression, t);
      if (heldFace != null) face.seek([{ t: 0, name: heldFace, isThroughBlink: false }], 0);
    };
    const pose = () => ({ rot, pos, scl, zoom, lids: lids(), expr: face.name, squashAnchor: anchor });
    const setClip = (c) => {
      playing = false; cur = c; time = 0; anchor = c.squashAnchor;
      inspect = { bias: c.inspect.bias ?? inspect.bias, isFollowingTurn: c.inspect.isFollowingTurn ?? inspect.isFollowingTurn };
    };
    const start = (entry) => {
      pending = null; setClip(entry.clip); loaded = { clip: entry.clip, name: entry.name }; looping = true;
      if (entry.isPlaying) {
        playing = true;
        if (entry.phase > 0) seek(entry.phase * entry.clip.duration);
        face.release();
        if (entry.phase <= 0) fireExpressions(-1e-9, 0);
      } else {
        seek(0);
        if (entry.isRest) gaze = { ...gaze, hold: 0 };
      }
    };
    const bridgeTo = (entry) => {
      const from = pose(), to = clipStartPose(entry.clip);
      pending = entry; setClip(bridgeClip(from, to)); looping = false; playing = true;
      if (heldFace == null && from.expr !== to.expr) whenEyesOpen(() => face.morph(to.expr));
    };
    const bridgeAtLoopEnd = () => {
      if (pending != null || loaded == null || posesMatch(pose(), clipStartPose(loaded.clip))) return false;
      bridgeTo({ ...loaded, isPlaying: true, phase: 0, isRest: false });
      return true;
    };
    const advanceClip = (dt) => {
      const t0 = time;
      let t1 = t0 + dt;
      if (t1 >= cur.duration) {
        fireExpressions(t0, cur.duration);
        if (looping) {
          loops += 1;
          if (bridgeAtLoopEnd()) return;
          t1 -= cur.duration;
          if (t1 >= cur.duration) t1 = 0;
          fireExpressions(-1e-9, t1);
          time = t1;
        } else {
          time = cur.duration; playing = false;
          if (pending != null) start(pending);
        }
      } else { fireExpressions(t0, t1); time = t1; }
      look = null;
      applyPose();
    };
    const approach = (a, b, t) => { const v = a + (b - a) * t; return Math.abs(b - v) < 0.001 ? b : v; };
    const updateGaze = (dt) => {
      if (paused || (!gaze.isHeld && gaze.hold === 0)) return;
      const t = 1 - 0.86 ** (dt * 60);
      gaze = { ...gaze, cx: approach(gaze.cx, gaze.x, t), cy: approach(gaze.cy, gaze.y, t), hold: approach(gaze.hold, +gaze.isHeld, t) };
      if (playing) return;
      applyPose();
      const g = gazePose(body, gaze.cx, gaze.cy), h = gaze.hold;
      rot = [rot[0] + (g.rx - rot[0]) * h, rot[1] + (g.ry - rot[1]) * h, rot[2] * (1 - h)];
      pos = [pos[0] + (g.px - pos[0]) * h, pos[1] + (g.py - pos[1]) * h];
    };
    const stepLook = (dt) => {
      if (look == null) return;
      const t = look.t + dt, u = Math.min(t / 0.5, 1), k = bezierEase(u, EASE_DEFAULT);
      rot = [0, 1, 2].map((i) => look.fromRot[i] + (look.toRot[i] - look.fromRot[i]) * k);
      pos = [0, 1].map((i) => look.fromPos[i] + (look.toPos[i] - look.fromPos[i]) * k);
      if (u >= 1) { rot = look.toRot; pos = look.toPos; look = null; } else look = { ...look, t };
    };
    const bodies = () => {
      if (fromBodies.length === 0) return [{ body, weight: 1 }];
      const w = easeInOutCubic(clamp(bodyBlend.x, 0, 1)), m = new Map();
      for (const b of fromBodies) m.set(b.body, (m.get(b.body) || 0) + b.weight * (1 - w));
      m.set(body, (m.get(body) || 0) + w);
      const list = [...m].filter(([, v]) => v > 1e-4), total = list.reduce((s, [, v]) => s + v, 0);
      return list.map(([b, v]) => ({ body: b, weight: v / total }));
    };
    const stepBody = (dt) => {
      if (fromBodies.length === 0) return;
      const n = subSteps(dt);
      for (let i = 0; i < n; i++) stepSpring(bodyBlend, 10, 1, dt / n);
      if (Math.abs(bodyBlend.x - 1) < 0.001 && Math.abs(bodyBlend.v) < 0.01) { bodyBlend.x = 1; bodyBlend.v = 0; fromBodies = []; }
    };
    const blinkNow = () => face.blinkAmount() ?? lids();
    const eyesFor = (yaw, weight) => {
      const pair = inspectScale(face.eyes(), weight, inspect, yaw), b = blinkNow();
      return b <= 1e-4 ? pair : [blinkShape(pair[0], b), blinkShape(pair[1], b)];
    };

    return {
      get isPlaying() { return playing; },
      get loopCount() { return loops; },
      get face() { return face.name; },
      get isSettled() {
        const gazeDone = paused || (gaze.hold === +gaze.isHeld && (!gaze.isHeld || (gaze.cx === gaze.x && gaze.cy === gaze.y)));
        return !playing && pokes.length === 0 && fromBodies.length === 0 && look == null && deferred == null &&
          !face.isMorphing && face.blinkAmount() == null && morph.snapshot().isSettled && gazeDone;
      },
      load(name, { isPlaying = true, transition = 'bridge', phase = 0 } = {}) {
        const entry = { clip: clip(name), name, isPlaying, phase: clamp(phase, 0, 1) % 1, isRest: false };
        if (transition === 'bridge' && loaded != null && (pending != null || loaded.name !== name)) bridgeTo(entry); else start(entry);
      },
      play() { paused = false; playing = true; },
      pause() { paused = true; playing = false; },
      rest() {
        paused = false;
        const entry = { clip: REST_CLIP, name: 'rest', isPlaying: false, phase: 0, isRest: true };
        if (pending == null && (loaded == null || loaded.name === 'rest')) { if (loaded == null) start(entry); } else bridgeTo(entry);
      },
      seek,
      setBody(next, { isInstant = false } = {}) {
        if (!isInstant) {
          if (next !== body) { fromBodies = bodies(); body = next; bodyBlend.x = 0; bodyBlend.v = 0; bodyBlend.t = 1; }
        } else { body = next; fromBodies = []; bodyBlend.x = 1; bodyBlend.v = 0; }
      },
      setMorph(name, { isInstant = false } = {}) { morph.set(name); if (isInstant) morph.settle(); },
      setExpression(name, { isThroughBlink = false } = {}) {
        const n = expressionName(name);
        whenEyesOpen(() => { if (isThroughBlink && !LIDLESS.has(n) && !LIDLESS.has(face.name)) face.lidMorph(n); else face.morph(n); });
      },
      holdFace(name) {
        if (name === heldFace) return;
        heldFace = name;
        whenEyesOpen(() => {
          const atTime = (keys, t) => { let n = 'neutral'; for (const k of keys) { if (k.t > t + 1e-9) break; n = k.name; } return n; };
          const want = heldFace ?? (pending == null ? atTime(cur.expression, time) : atTime(pending.clip.expression, 0));
          if (want !== face.name) face.morph(want);
        });
      },
      poke(kind, { turns = 1 } = {}) {
        if (!POKES.includes(kind)) return;
        pokes = [...pokes, { poke: kind, t: 0, turns: Math.max(1, Math.round(turns)) }];
      },
      blink() { face.blink(); },
      setGaze(g) {
        if (g == null) { gaze = { ...gaze, isHeld: false }; return; }
        const x = clamp(g[0] || 0, -1, 1), y = clamp(g[1] || 0, -1, 1);
        gaze = gaze.hold === 0 ? { ...gaze, isHeld: true, x, y, cx: x, cy: y } : { ...gaze, isHeld: true, x, y };
      },
      setGazeAlways(on) { gaze = { ...gaze, isAlways: !!on }; },
      look(dir) {
        const t = LOOKS[dir] || LOOKS.center;
        look = { t: 0, fromRot: rot, toRot: t.rot, fromPos: pos, toPos: t.pos };
      },
      advance(dt) {
        const h = Math.min(dt, 0.1);
        updateGaze(h);
        if (playing) advanceClip(h * (1 - morph.snapshot().amount));
        stepLook(h);
        face.step(h);
        if (deferred != null && blinkNow() === 0) { const fn = deferred; deferred = null; fn(); }
        updateLidLock();
        stepBody(h);
        pokes = pokes.map((p) => ({ ...p, t: p.t + h })).filter((p) => p.t < pokeLength(p));
        morph.advance(h);
        const m = morph.snapshot();
        if (m.amount > 0 || !m.isSettled) spinBase = spinBase || rot.map((a) => 360 * Math.round(a / 360)); else spinBase = null;
      },
      frame() {
        const g = gaze.isAlways && playing && !paused ? gazePose(body, gaze.cx, gaze.cy) : null;
        const gw = 0.55 * gaze.hold, poke = pokeOffsets(pokes);
        const r = [rot[0] + (g ? g.rx * gw : 0) + poke.pitch, rot[1] + (g ? g.ry * gw : 0) + poke.yaw, rot[2]];
        const p = [pos[0] + (g ? g.px * gw : 0), pos[1] + (g ? g.py * gw : 0) + poke.lift];
        const s = [scl[0] * poke.squash[0], scl[1] * poke.squash[1]];
        const weight = face.inspectWeight(), m = morph.snapshot(), keep = 1 - m.amount;
        const spinDeg = (m.spin % TAU) / DEG, base = spinBase || [0, 0, 0];
        const blend = (i) => base[i] + (r[i] - base[i]) * keep;
        const yaw = blend(1);
        return {
          body,
          quat: quatFromEuler(blend(0) * DEG, (yaw + spinDeg) * DEG, blend(2) * DEG),
          zoom,
          offset: keep === 1 ? p : [p[0] * keep, p[1] * keep],
          squash: keep === 1 ? s : [1 + (s[0] - 1) * keep, 1 + (s[1] - 1) * keep],
          squashAnchor: anchor,
          eyes: m.amount >= 0.5 ? null : eyesFor(yaw, weight),
          bodies: bodies(),
          morph: m.kind === null && m.isSettled ? null : m,
        };
      },
    };
  }

