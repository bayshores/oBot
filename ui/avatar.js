  // 11. Morph overlay driver: springs for "amount", "swap" and "spin"
  // ===========================================================================

  const MORPH_KINDS = {
    thinking: 'dots', orbit: 'orbit', radar: 'radar', progress: 'progress', spawning: 'gather', dictating: 'wave',
    sending: 'send', receiving: 'receive', uploading: 'dock', bouncing: 'ball', writing: 'pencil', alerting: 'bang',
    'powering-down': 'standby',
  };
  const CYCLING_MORPHS = { progress: 2.5, spawning: 2 };

  function createMorphDriver({ seed = 2654435769, reduced = false } = {}) {
    const rand = mulberry32(seed);
    const amount = spring(0), swap = spring(1), spin = spring(0);
    let target = null, lastTarget = null, kind = null, outgoing = null;
    let released = false, releasedAt = 0, spinTotal = 0, spinDir = 1, wasOn = false;
    let clock = 0, stateStart = 0, shotStart = 0, outStateStart = 0, outShotStart = 0;
    const update = () => {
      const k = target == null ? null : MORPH_KINDS[target] || null;
      const prevShot = shotStart;
      if (target !== lastTarget) { lastTarget = target; if (target != null) { shotStart = clock; released = false; } }
      let on = k != null;
      if (target != null && CYCLING_MORPHS[target] != null) {
        // progress / spawning: show for a while, let the face show for 1.5 s, repeat.
        if (!released && clock - shotStart > CYCLING_MORPHS[target]) { released = true; releasedAt = clock; } else if (released && clock - releasedAt > 1.5) { released = false; shotStart = clock; }
        on = !released;
      }
      amount.t = +on;
      if (k != null && k !== kind) {
        if (kind != null && amount.x > 0.02) { outgoing = kind; outStateStart = stateStart; outShotStart = prevShot; swap.x = +reduced; } else { outgoing = null; swap.x = 1; }
        swap.v = 0; swap.t = 1; kind = k; stateStart = clock;
      }
      if (k == null && amount.x < 0.004) { kind = null; outgoing = null; }
      if (swap.x > 0.996) outgoing = null;
      if (on !== wasOn) {
        if (on && !reduced) spinDir = rand() < 0.5 ? 1 : -1;
        if (!reduced) { spinTotal += Math.PI * spinDir; spin.t = spinTotal; }
        wasOn = on;
      }
    };
    return {
      set(name) { target = name; },
      advance(dt) {
        const h = dt > 0 ? Math.min(dt, 0.1) : 0;
        clock += h;
        update();
        const n = subSteps(h), step = h / n;
        for (let i = 0; i < n; i++) { stepSpring(amount, 14, 1, step); stepSpring(swap, 11, 1, step); stepSpring(spin, 14, 1, step); }
        if (reduced) { swap.x = 1; spin.x = spin.t; amount.x = amount.t; }
      },
      settle() {
        update();
        for (const s of [amount, swap, spin]) { s.x = s.t; s.v = 0; }
        update();
      },
      snapshot() {
        return {
          amount: clamp(amount.x, 0, 1), spin: spin.x, kind, outgoing, swap: clamp(swap.x, 0, 1),
          clock: { stateTime: clock - stateStart, shotTime: clock - shotStart },
          outgoingClock: { stateTime: clock - outStateStart, shotTime: clock - outShotStart },
          isReducedMotion: reduced,
          isSettled: Math.abs(amount.x - amount.t) < 0.001 && Math.abs(spin.t - spin.x) < 0.01 && swap.x > 0.996,
        };
      },
    };
  }

