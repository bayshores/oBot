  /** Seeded Fisher-Yates shuffle; the first pick is never `avoid`. */
  function shuffled(list, rand, avoid) {
    const out = [...list];
    for (let i = out.length - 1; i > 0; --i) {
      const j = Math.floor(rand() * (i + 1));
      [out[i], out[j]] = [out[j], out[i]];
    }
    const k = out.findIndex((c) => c !== avoid);
    if (k > 0) [out[0], out[k]] = [out[k], out[0]];
    return out;
  }

  function createDirector(anim, initial, { seed = 1, isCompact = false, isResting = false, firstPhase } = {}) {
    const rand = mulberry32(seed);
    const bags = new Map();
    let compact = isCompact, resting = isResting, emphasized = false, started = resting;
    let state = initial, entry = STATE_TABLE[initial], elapsed = 0, step = 0, lastLoops = anim.loopCount, current = null;
    const clips = () => (compact && entry.compactClips != null ? entry.compactClips : entry.clips);
    const sequential = () => entry.next != null && entry.holdSeconds == null;
    const draw = () => {
      const list = clips(), bag = bags.get(list) || [];
      if (bag.length === 0) bag.push(...shuffled(list, rand, current));
      bags.set(list, bag);
      return bag.shift();
    };
    const playNext = () => {
      const name = sequential() ? clips()[step] : draw();
      lastLoops = anim.loopCount;
      if (name === undefined || name === current) return;
      const fromStart = started || sequential();
      anim.load(name, { phase: fromStart ? 0 : firstPhase ?? rand() });
      started = true; current = name; lastLoops = anim.loopCount;
    };
    const applyFace = () => anim.holdFace(entry.face ?? (emphasized ? 'surprised' : null));
    const enter = (s) => {
      state = s; entry = STATE_TABLE[s]; elapsed = 0; step = 0;
      anim.setMorph(entry.morph ?? null);
      applyFace();
      if (!resting) playNext();
    };
    if (resting) anim.rest();
    enter(initial);
    return {
      get state() { return state; },
      get clip() { return current; },
      setState(s) { if (s !== state) enter(s); },
      setCompact(v) { compact = v; },
      setEmphasis(v) { if (v !== emphasized) { emphasized = v; applyFace(); } },
      setResting(v) {
        if (v === resting) return;
        resting = v;
        if (resting) { anim.rest(); current = null; } else playNext();
      },
      advance(dt) {
        if (resting) return;
        elapsed += dt;
        const next = entry.next;
        if (next != null && entry.holdSeconds != null && elapsed >= entry.holdSeconds) enter(next);
        else if (anim.loopCount !== lastLoops) {
          if (next != null && entry.holdSeconds == null && (step += 1) >= clips().length) enter(next); else playNext();
        }
      },
    };
  }

