  const unitDirs = (n) => Array.from({ length: n }, (_, i) => {
    const a = (i / n) * TAU;
    return { x: Math.cos(a), y: Math.sin(a) };
  });
  const RAYS_160 = unitDirs(160);
  const RAYS_480 = unitDirs(480);

  /** Pixels per model unit for a solid drawn in a box of `box` px. */
  const unitPx = (sol, box) => Math.max(0.2, sol.size) * ((0.36 * box) / 1.18);

  /** Rotate a point: yaw about Y, then pitch about X, then roll about Z (angles in radians). */
  function rotator(yaw, pitch, roll) {
    const cy = Math.cos(yaw), sy = Math.sin(yaw);
    const cp = Math.cos(pitch), sp = Math.sin(pitch);
    const cr = Math.cos(roll), sr = Math.sin(roll);
    return ({ x, y, z }) => {
      const x1 = x * cy + z * sy, z1 = z * cy - x * sy;
      const y2 = y * cp - z1 * sp, z2 = z1 * cp + y * sp;
      return { x: x1 * cr - y2 * sr, y: y2 * cr + x1 * sr, z: z2 };
    };
  }

  /** Orthographic camera looking down -z, +y up, centred in a square box. */
  function makeView(sol, angles, box) {
    const half = box / 2, k = unitPx(sol, box);
    const rotate = rotator(angles.yaw * DEG, angles.pitch * DEG, angles.roll * DEG);
    return {
      rotate,
      project: (p) => { const q = rotate(p); return { x: half + k * q.x, y: half - k * q.y }; },
      origin: { x: half, y: half },
      radius: k,
    };
  }

  /** Points -> flat [x0, y0, x1, y1, ...]; [] when unusable. */
  function flatLoop(pts) {
    if (pts.length < 2 || !Number.isFinite(pts[0].x) || !Number.isFinite(pts[0].y)) return [];
    const out = [];
    for (const p of pts) if (Number.isFinite(p.x) && Number.isFinite(p.y)) out.push(p.x, p.y);
    return out.length >= 6 ? [out] : [];
  }

  function convexHull(points) {
    const pts = points.filter((p) => Number.isFinite(p.x) && Number.isFinite(p.y)).sort((a, b) => a.x - b.x || a.y - b.y);
    if (pts.length < 3) return pts;
    const cross = (o, a, b) => (a.x - o.x) * (b.y - o.y) - (a.y - o.y) * (b.x - o.x);
    const lower = [], upper = [];
    for (const p of pts) {
      while (lower.length >= 2 && cross(lower[lower.length - 2], lower[lower.length - 1], p) <= 0) lower.pop();
      lower.push(p);
    }
    for (let i = pts.length - 1; i >= 0; i--) {
      const p = pts[i];
      while (upper.length >= 2 && cross(upper[upper.length - 2], upper[upper.length - 1], p) <= 0) upper.pop();
      upper.push(p);
    }
    lower.pop(); upper.pop();
    return lower.concat(upper);
  }

  /** Outline of a point cloud and/or a set of balls. */
  function solidOutline(sil, view) {
    const pts = [];
    for (const s of sil.samples) {
      const p = view.project(s);
      if (Number.isFinite(p.x) && Number.isFinite(p.y)) pts.push(p);
    }
    if (sil.balls.length === 0) return convexHull(pts);
    const balls = sil.balls
      .map(([x, y, z, r]) => ({ ...view.project({ x, y, z }), r: r * view.radius }))
      .filter((b) => Number.isFinite(b.x) && Number.isFinite(b.y) && b.r > 1e-6);
    let cx = view.origin.x, cy = view.origin.y;
    if (balls.length > 0) {
      cx = 0; cy = 0;
      for (const b of balls) { cx += b.x; cy += b.y; }
      cx /= balls.length; cy /= balls.length;
    }
    for (const { x: dx, y: dy } of RAYS_160) {
      let reach = 0;
      for (const b of balls) {
        const ox = b.x - cx, oy = b.y - cy;
        const proj = dx * ox + dy * oy;
        const disc = proj * proj - (ox * ox + oy * oy) + b.r * b.r;
        if (disc <= 0) continue;
        const t = proj + Math.sqrt(disc);
        if (t > reach) reach = t;
      }
      if (reach > 0) pts.push({ x: cx + dx * reach, y: cy + dy * reach });
    }
    if (sil.samples.length > 0) return convexHull(pts);
    if (pts.length >= 3) return pts;
    for (const b of balls) {
      for (let i = 0; i < 48; i++) {
        const a = (i / 48) * TAU;
        pts.push({ x: b.x + b.r * Math.cos(a), y: b.y + b.r * Math.sin(a) });
      }
    }
    return pts.length >= 3 ? convexHull(pts) : pts;
  }

  /** Outline of a loft: farthest edge crossing in each of 480 angular bins around the box centre. */
  function loftOutline(rings3d, view) {
    const rings = rings3d.map((r) => r.map(view.project));
    const centroid = (r) => {
      let x = 0, y = 0;
      for (const p of r) { x += p.x; y += p.y; }
      return { x: x / r.length, y: y / r.length };
    };
    const back = centroid(rings[0]), front = centroid(rings[rings.length - 1]);
    if (Math.hypot(front.x - back.x, front.y - back.y) < 1e-4) {
      // Seen straight on: the biggest ring is the outline.
      let best = rings[0], area = 0;
      for (const r of rings) {
        let a = 0;
        for (let i = 0; i < r.length; i++) { const p = r[i], q = r[(i + 1) % r.length]; a += p.x * q.y - q.x * p.y; }
        if (Math.abs(a) > area) { best = r; area = Math.abs(a); }
      }
      return best;
    }
    const o = view.origin, B = 480;
    const binOf = rings.map((r) => r.map((p) => Math.floor((((Math.atan2(p.y - o.y, p.x - o.x) + TAU) % TAU) / TAU) * B) % B));
    const dist2 = rings.map((r) => r.map((p) => (p.x - o.x) ** 2 + (p.y - o.y) ** 2));
    const reach = new Float64Array(B);
    let floor = 0;
    const addEdge = (p, q, bp, bq, far2) => {
      if (floor > 0 && Math.sqrt(far2) < (floor - 0.01) / 1.01) return;
      let span = bq - bp;
      if (span > B / 2) span -= B; else if (span < -B / 2) span += B;
      const dir = span < 0 ? -1 : 1, n = Math.abs(span);
      const ex = q.x - p.x, ey = q.y - p.y, ox = p.x - o.x, oy = p.y - o.y;
      for (let k = -1; k <= n + 1; k++) {
        const b = (bp + dir * k + B) % B;
        const { x: c, y: s } = RAYS_480[b];
        const den = c * ey - s * ex;
        if (Math.abs(den) < 1e-9) continue;
        const d = (ox * ey - oy * ex) / den, u = (ox * s - oy * c) / den;
        if (d > reach[b] && u >= 0 && u <= 1) reach[b] = d;
      }
    };
    const maxPer = dist2.map((r) => Math.max(...r));
    const order = maxPer.map((_, i) => i).sort((a, b) => maxPer[b] - maxPer[a]);
    for (const ri of order) {
      const r = rings[ri];
      for (let i = 0; i < r.length; i++) {
        const j = (i + 1) % r.length;
        addEdge(r[i], r[j], binOf[ri][i], binOf[ri][j], Math.max(dist2[ri][i], dist2[ri][j]));
      }
      floor = Math.min(...reach);
    }
    for (let ri = 0; ri < rings.length - 1; ri++) {
      const a = rings[ri], b = rings[ri + 1];
      for (let i = 0; i < Math.min(a.length, b.length); i++) {
        addEdge(a[i], b[i], binOf[ri][i], binOf[ri + 1][i], Math.max(dist2[ri][i], dist2[ri + 1][i]));
      }
    }
    const out = [];
    for (let b = 0; b < B; b++) if (reach[b] > 0) out.push({ x: o.x + RAYS_480[b].x * reach[b], y: o.y + RAYS_480[b].y * reach[b] });
    return out;
  }

  /** Projected outline polygons of a solid (flat arrays, px in a `box` sized square). */
  function silhouettePolys(sol, angles, box) {
    const sil = sol.silhouette, view = makeView(sol, angles, box);
    if (sil.kind === 'extrusion' && sil.convex) return flatLoop(convexHull(sil.rings.flat().map(view.project)));
    if (sil.kind === 'loft') return flatLoop(loftOutline(sil.rings, view));
    if (sil.kind === 'solid') return flatLoop(solidOutline(sil, view));
    // Concave extrusion: both caps plus every side quad; merged by polygonUnion().
    const rings = sil.rings.map((r) => r.map(view.project));
    const polys = [rings[rings.length - 1], rings[0]];
    for (let e = 1; e < rings.length; e++) {
      const a = rings[e - 1], b = rings[e];
      for (let i = 0; i < b.length; i++) {
        const j = (i + 1) % b.length;
        polys.push([a[i], a[j], b[j], b[i]]);
      }
    }
    return polys.flatMap(flatLoop);
  }

  /** "M x y x y ... Z" for each loop, 2 decimals. */
  function loopsPath(loops) {
    let d = '';
    for (const l of loops) {
      d += `M${fmt2(l[0])} ${fmt2(l[1])}`;
      for (let i = 2; i < l.length; i += 2) d += ` ${fmt2(l[i])} ${fmt2(l[i + 1])}`;
      d += 'Z';
    }
    return d;
  }

  // --- Polygon union on an integer grid (concave extrusions: star, sparkle, clover, flower) ---

  const UNION_GRID = 1024;
  const KEY_SPAN = 2 ** 26;

  class VertexIndex {
    constructor() { this.xs = []; this.ys = []; this.map = new Map(); }
    id(x, y) {
      const key = (x + 2 ** 23) * 2 ** 25 + (y + 2 ** 23);
      let i = this.map.get(key);
      if (i === undefined) { i = this.xs.length; this.xs.push(x); this.ys.push(y); this.map.set(key, i); }
      return i;
    }
  }
  const orient = (ax, ay, bx, by, px, py) => (bx - ax) * (py - ay) - (by - ay) * (px - ax);

  /** Where segment a-b properly crosses c-d, rounded to the grid; null if it does not. */
  function crossing(ax, ay, bx, by, cx, cy, dx, dy) {
    const s1 = Math.sign(orient(ax, ay, bx, by, cx, cy)), s2 = Math.sign(orient(ax, ay, bx, by, dx, dy));
    const u = orient(cx, cy, dx, dy, ax, ay), v = orient(cx, cy, dx, dy, bx, by);
    if (!(s1 * s2 < 0 && Math.sign(u) * Math.sign(v) < 0)) return null;
    const t = u / (u - v);
    return [Math.round(ax + (bx - ax) * t), Math.round(ay + (by - ay) * t)];
  }

  function polygonUnion(polys) {
    // 1. Directed edges of every polygon, all turned the same way; shared edges cancel out.
    const verts = new VertexIndex();
    const counts = new Map();
    const addPoly = (q) => {
      let area = 0;
      for (let i = 0; i < q.length; i += 2) { const j = (i + 2) % q.length; area += q[i] * q[j + 1] - q[j] * q[i + 1]; }
      if (area === 0) return;
      const n = q.length / 2, ids = [];
      for (let k = 0; k < n; k++) { const i = area > 0 ? k : n - 1 - k; ids.push(verts.id(q[2 * i], q[2 * i + 1])); }
      for (let k = 0; k < n; k++) {
        const a = ids[k], b = ids[(k + 1) % n];
        if (a === b) continue;
        const rev = b * KEY_SPAN + a, c = counts.get(rev) || 0;
        if (c > 1) counts.set(rev, c - 1);
        else if (c === 1) counts.delete(rev);
        else counts.set(a * KEY_SPAN + b, (counts.get(a * KEY_SPAN + b) || 0) + 1);
      }
    };
    for (const p of polys) {
      const q = p.map((v) => Math.round(v * UNION_GRID));
      if (q.length === 8) {
        // A folded (bow-tie) quad becomes two triangles.
        const [x0, y0, x1, y1, x2, y2, x3, y3] = q;
        let hit = crossing(x0, y0, x1, y1, x2, y2, x3, y3);
        if (hit) { addPoly([x0, y0, hit[0], hit[1], x3, y3]); addPoly([hit[0], hit[1], x1, y1, x2, y2]); continue; }
        hit = crossing(x1, y1, x2, y2, x3, y3, x0, y0);
        if (hit) { addPoly([x1, y1, hit[0], hit[1], x0, y0]); addPoly([hit[0], hit[1], x2, y2, x3, y3]); continue; }
      }
      addPoly(q);
    }
    let edges = [...counts].map(([key, count]) => {
      const a = Math.floor(key / KEY_SPAN), b = key - a * KEY_SPAN;
      return { ax: verts.xs[a], ay: verts.ys[a], bx: verts.xs[b], by: verts.ys[b], count };
    });

    // 2. Every vertex plus every crossing point, sorted by x.
    const pointIndex = new VertexIndex();
    for (const e of edges) { pointIndex.id(e.ax, e.ay); pointIndex.id(e.bx, e.by); }
    const minX = (e) => Math.min(e.ax, e.bx);
    const byX = edges.map((_, i) => i).sort((i, j) => minX(edges[i]) - minX(edges[j]));
    for (let k = 0; k < byX.length; k++) {
      const a = edges[byX[k]], maxX = Math.max(a.ax, a.bx);
      for (let m = k + 1; m < byX.length; m++) {
        const b = edges[byX[m]];
        if (minX(b) > maxX) break;
        if (Math.min(b.ay, b.by) > Math.max(a.ay, a.by) || Math.max(b.ay, b.by) < Math.min(a.ay, a.by)) continue;
        const hit = crossing(a.ax, a.ay, a.bx, a.by, b.ax, b.ay, b.bx, b.by);
        if (hit) pointIndex.id(hit[0], hit[1]);
      }
    }
    const points = pointIndex.xs.map((x, i) => ({ x, y: pointIndex.ys[i] })).sort((p, q) => p.x - q.x);
    const firstAtX = (x) => {
      let lo = 0, hi = points.length;
      while (lo < hi) { const mid = (lo + hi) >> 1; if (points[mid].x < x) lo = mid + 1; else hi = mid; }
      return lo;
    };

    // 3. Split edges at every point lying on them, then merge duplicates.
    const pieces = [];
    for (const e of edges) {
      const dx = e.bx - e.ax, dy = e.by - e.ay, l1 = Math.abs(dx) + Math.abs(dy);
      const y0 = Math.min(e.ay, e.by) - 0.5, y1 = Math.max(e.ay, e.by) + 0.5, x1 = Math.max(e.ax, e.bx) + 0.5;
      const on = [];
      for (let i = firstAtX(Math.min(e.ax, e.bx) - 0.5); i < points.length && points[i].x <= x1; i++) {
        const { x, y } = points[i];
        if (y < y0 || y > y1 || 2 * Math.abs(orient(e.ax, e.ay, e.bx, e.by, x, y)) > l1) continue;
        on.push({ t: ((x - e.ax) * dx + (y - e.ay) * dy) / (dx * dx + dy * dy), x, y });
      }
      on.sort((p, q) => p.t - q.t);
      for (let i = 1; i < on.length; i++) {
        const p = on[i - 1], q = on[i];
        if (p.x !== q.x || p.y !== q.y) pieces.push({ ax: p.x, ay: p.y, bx: q.x, by: q.y, count: e.count });
      }
    }
    const merged = new VertexIndex();
    const sums = new Map();
    for (const p of pieces) {
      const a = merged.id(p.ax, p.ay), b = merged.id(p.bx, p.by);
      const key = Math.min(a, b) * KEY_SPAN + Math.max(a, b);
      sums.set(key, (sums.get(key) || 0) + (a < b ? p.count : -p.count));
    }
    edges = [];
    for (const [key, c] of sums) {
      if (c === 0) continue;
      const a = Math.floor(key / KEY_SPAN), b = key - a * KEY_SPAN;
      edges.push({ ax: merged.xs[a], ay: merged.ys[a], bx: merged.xs[b], by: merged.ys[b], count: c });
    }

    // 4. Keep edges with filled area on exactly one side (winding number test at the midpoint).
    const boundary = [];
    for (const e of edges) {
      const mx = e.ax + e.bx, my = e.ay + e.by; // doubled coordinates stay integral
      let wind = 0;
      for (const f of edges) {
        if (f === e) continue;
        const fy0 = 2 * f.ay, fy1 = 2 * f.by;
        if (fy0 <= my) {
          if (fy1 > my && orient(2 * f.ax, fy0, 2 * f.bx, fy1, mx, my) > 0) wind += f.count;
        } else if (fy1 <= my && orient(2 * f.ax, fy0, 2 * f.bx, fy1, mx, my) < 0) wind -= f.count;
      }
      const sideA = e.ay < e.by || (e.ay === e.by && e.ax > e.bx) ? wind + e.count : wind;
      const sideB = sideA - e.count;
      if ((sideA !== 0) !== (sideB !== 0)) {
        boundary.push(sideA === 0 ? { ax: e.bx, ay: e.by, bx: e.ax, by: e.ay, count: 1 } : { ...e, count: 1 });
      }
    }

    // 5. Chain the boundary edges into closed loops.
    const idx = new VertexIndex();
    const next = [];
    for (const e of boundary) {
      const a = idx.id(e.ax, e.ay), b = idx.id(e.bx, e.by);
      while (next.length <= Math.max(a, b)) next.push([]);
      next[a].push(b);
    }
    let d = '';
    next.forEach((outs, start) => {
      while (outs.length > 0) {
        d += `M${fmt2(idx.xs[start] / UNION_GRID)} ${fmt2(idx.ys[start] / UNION_GRID)}`;
        let v = outs.pop();
        while (v != null && v !== start) {
          d += ` ${fmt2(idx.xs[v] / UNION_GRID)} ${fmt2(idx.ys[v] / UNION_GRID)}`;
          v = next[v].pop();
        }
        d += 'Z';
      }
    });
    return d;
  }

  // ===========================================================================
  // 7. Eyes: expressions, morphing and blinking
  // ===========================================================================
  //
  // One eye = { off:[x,y], tilt, wid, lidY, oval:[rx,ry], ovalMix, pts, path, fillRing }.
  // Units: 1 = body radius, +y up, +x points away from the face centre (mirrored
  // for the left eye). `pts` is the centre line; `wid` its half thickness.

  const EYE_WIDTH = 0.26;      // neutral eye width
  const EYE_HEIGHT = 0.57;     // neutral eye height
  const EYE_GAP = 0.64;        // neutral distance between eye centres
  const ARC_HALF_WIDTH = 0.1305;
  const FACE_CHANGE_S = 0.28;  // expression change
  const BRIDGE_S = 0.35;       // clip bridge and "change through a blink"
  const BLINK_S = 0.26;

  /** Three points -> 2 cubic Beziers as 18 numbers (3 anchors x {x, y, inDx, inDy, outDx, outDy}). */
  function curveThrough({ p0, p1, p2, isArc }) {
    const [x0, y0] = p0, [x1, y1] = p1, [x2, y2] = p2;
    const out = new Array(18).fill(0);
    const anchor = (i, p) => { out[i * 6] = p[0]; out[i * 6 + 1] = p[1]; };
    const handleIn = (i, p) => { out[i * 6 + 2] = p[0] - out[i * 6]; out[i * 6 + 3] = p[1] - out[i * 6 + 1]; };
    const handleOut = (i, p) => { out[i * 6 + 4] = p[0] - out[i * 6]; out[i * 6 + 5] = p[1] - out[i * 6 + 1]; };
    if (isArc) {
      const den = 2 * (x0 * (y1 - y2) + x1 * (y2 - y0) + x2 * (y0 - y1));
      if (Math.abs(den) > 1e-9) {
        // Circular arc through the three points.
        const s0 = x0 * x0 + y0 * y0, s1 = x1 * x1 + y1 * y1, s2 = x2 * x2 + y2 * y2;
        const cx = (s0 * (y1 - y2) + s1 * (y2 - y0) + s2 * (y0 - y1)) / den;
        const cy = (s0 * (x2 - x1) + s1 * (x0 - x2) + s2 * (x1 - x0)) / den;
        const r = Math.hypot(x0 - cx, y0 - cy);
        const a0 = Math.atan2(y0 - cy, x0 - cx), a2 = Math.atan2(y2 - cy, x2 - cx), a1 = Math.atan2(y1 - cy, x1 - cx);
        const full = (a2 - a0 + TAU) % TAU;
        const sweep = (a1 - a0 + TAU) % TAU <= full ? full : full - TAU;
        const half = sweep / 2, k = (4 / 3) * Math.tan(half / 4) * r;
        const angles = [a0, a0 + half, a0 + sweep];
        for (let i = 0; i < 3; i++) {
          const a = angles[i], p = [cx + r * Math.cos(a), cy + r * Math.sin(a)], t = [-Math.sin(a), Math.cos(a)];
          anchor(i, p);
          if (i > 0) handleIn(i, [p[0] - k * t[0], p[1] - k * t[1]]);
          if (i < 2) handleOut(i, [p[0] + k * t[0], p[1] + k * t[1]]);
        }
        return out;
      }
      const m = [(x0 + x2) / 2, (y0 + y2) / 2];
      anchor(0, [x0, y0]); anchor(1, m); anchor(2, [x2, y2]);
      handleOut(0, [x0 + (m[0] - x0) / 3, y0 + (m[1] - y0) / 3]);
      handleIn(1, [m[0] - (m[0] - x0) / 3, m[1] - (m[1] - y0) / 3]);
      handleOut(1, [m[0] + (x2 - m[0]) / 3, m[1] + (y2 - m[1]) / 3]);
      handleIn(2, [x2 - (x2 - m[0]) / 3, y2 - (y2 - m[1]) / 3]);
      return out;
    }
    // Quadratic with control p1, split at its middle into two cubics.
    const a = [(x0 + x1) / 2, (y0 + y1) / 2], b = [(x1 + x2) / 2, (y1 + y2) / 2], m = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
    anchor(0, [x0, y0]); anchor(1, m); anchor(2, [x2, y2]);
    handleOut(0, [x0 + (2 / 3) * (a[0] - x0), y0 + (2 / 3) * (a[1] - y0)]);
    handleIn(1, [m[0] + (2 / 3) * (a[0] - m[0]), m[1] + (2 / 3) * (a[1] - m[1])]);
    handleOut(1, [m[0] + (2 / 3) * (b[0] - m[0]), m[1] + (2 / 3) * (b[1] - m[1])]);
    handleIn(2, [x2 + (2 / 3) * (b[0] - x2), y2 + (2 / 3) * (b[1] - y2)]);
    return out;
  }

  const pathAnchor = (p, i) => [p[i * 6], p[i * 6 + 1]];
  const pathHandle = (p, i, out) => { const k = out ? 4 : 2; return [p[i * 6] + p[i * 6 + k], p[i * 6 + 1] + p[i * 6 + k + 1]]; };
  const cubicAt = (a, b, c, d, t) => {
    const m = 1 - t;
    return [
      m * m * m * a[0] + 3 * m * m * t * b[0] + 3 * m * t * t * c[0] + t * t * t * d[0],
      m * m * m * a[1] + 3 * m * m * t * b[1] + 3 * m * t * t * c[1] + t * t * t * d[1],
    ];
  };
  const cubicTangent = (a, b, c, d, t) => {
    const m = 1 - t;
    return [
      3 * m * m * (b[0] - a[0]) + 6 * m * t * (c[0] - b[0]) + 3 * t * t * (d[0] - c[0]),
      3 * m * m * (b[1] - a[1]) + 6 * m * t * (c[1] - b[1]) + 3 * t * t * (d[1] - c[1]),
    ];
  };

  /** 21 centre-line points sampled from the 2-segment curve. */
  function centreLine(path) {
    const out = [];
    for (let seg = 0; seg < 2; seg++) {
      const a = pathAnchor(path, seg), b = pathHandle(path, seg, true), c = pathHandle(path, seg + 1, false), d = pathAnchor(path, seg + 1);
      for (let k = seg === 0 ? 0 : 1; k < 11; k++) out.push(cubicAt(a, b, c, d, k / 10));
    }
    return out;
  }

  function curveEye(off, tilt, wid, curve, oval) {
    const path = curveThrough(curve);
    return { off, tilt, wid, lidY: 1, oval, ovalMix: 0, pts: centreLine(path), path, fillRing: null };
  }
  /** Capsule `w` wide and `h` tall, tilted by angleDeg (top leans outward for positive angles). */
  function capsuleEye(w, h, angleDeg, off, tilt) {
    const half = Math.max(0, (h - w) / 2), a = angleDeg * DEG;
    const s = Math.sin(a) * half, c = Math.cos(a) * half;
    return curveEye(off, tilt, w / 2, { p0: [-s, -c], p1: [0, 0], p2: [s, c], isArc: false }, [0, 0]);
  }
  const pillEye = (w, h, angleDeg, offX) => capsuleEye(w, h, angleDeg, [offX, 0], 0);
  const ovalEye = (rx, ry, offX) => curveEye([offX, 0], 0, ry, { p0: [-rx, 0], p1: [0, 0], p2: [rx, 0], isArc: false }, [rx, ry]);
  const both = (e) => [e, e];

  const EXPRESSIONS = {
    neutral: both(pillEye(EYE_WIDTH, 0.57, 0, 0)),
    happy: both(curveEye([0.03, 0.03], 0, ARC_HALF_WIDTH, { p0: [0.16, -0.04], p1: [0, 0.12], p2: [-0.16, -0.04], isArc: true }, [0, 0])),
    surprised: both(pillEye(0.42, 0.86, 0, 0.03)),
    inspecting: [pillEye(0.54, 0.54, 0, 0.04), pillEye(0.36, 0.36, 0, 0.04)],
    sad: both(pillEye(EYE_WIDTH, 0.5, -28, -0.05)),
    sleepy: both(curveEye([0.01, 0], 0, EYE_WIDTH / 2, { p0: [-0.11, 0.025], p1: [0, -0.05], p2: [0.11, 0.025], isArc: false }, [0, 0])),
    squinted: both(pillEye(EYE_WIDTH, 0.5, 90, 0.01)),
    calm: both(ovalEye(0.296, 0.247, 0.05)),
    confused: both(curveEye([-0.1, 0], 0, ARC_HALF_WIDTH, { p0: [0.01, 0.16], p1: [-0.17, 0], p2: [0.01, -0.16], isArc: false }, [0, 0])),
  };
  const EXPRESSION_ALIASES = {
    thinking: 'sad', strange: 'inspecting', angry: 'neutral', inspect: 'inspecting',
    squint: 'squinted', idle: 'neutral', smile: 'happy', sleep: 'sleepy',
  };
  /** Faces that never blink and never change "through a blink". */
  const LIDLESS = new Set(['sad', 'happy', 'confused', 'squinted', 'sleepy']);

  function expressionName(name) {
    const n = String(name).trim().toLowerCase();
    const m = EXPRESSION_ALIASES[n] || n;
    return EXPRESSIONS[m] ? m : 'neutral';
  }
  const isOval = (e) => e.oval[0] > 1e-4 && e.oval[1] > 1e-4;
  const canBlink = (name) => !LIDLESS.has(name) && !EXPRESSIONS[name].some(isOval);
  const pairMap = (pair, f) => [f(pair[0], 0), f(pair[1], 1)];
  const plain = (e) => ({ ...e, ovalMix: 0 });

  /** True if the centre line bends noticeably (arcs, curves). */
  function isCurved(e) {
    if (isOval(e) || e.pts.length < 3) return false;
    const a = e.pts[0], b = e.pts[e.pts.length - 1];
    const dx = b[0] - a[0], dy = b[1] - a[1], len2 = dx * dx + dy * dy;
    if (len2 < 1e-8) return false;
    let worst = 0;
    for (const p of e.pts) {
      const t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len2;
      worst = Math.max(worst, Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy)));
    }
    return worst > Math.max(0.012, e.wid * 0.2);
  }

  const lerp2 = (a, b, t) => [lerp(a[0], b[0], t), lerp(a[1], b[1], t)];
  function resample(pts, i, n) {
    if (pts.length === 0) return [0, 0];
    if (pts.length === 1 || n <= 1) return pts[0];
    const f = (i / (n - 1)) * (pts.length - 1), k = Math.min(Math.floor(f), pts.length - 2);
    return lerp2(pts[k], pts[k + 1], f - k);
  }

  /** "spine" morph: lerp the curve anchors point by point. */
  function morphSpine(a, b, t) {
    const base = {
      off: lerp2(a.off, b.off, t), tilt: lerp(a.tilt, b.tilt, t), wid: lerp(a.wid, b.wid, t),
      lidY: lerp(a.lidY, b.lidY, t), oval: lerp2(a.oval, b.oval, t), ovalMix: 0, fillRing: null,
    };
    if (a.path && b.path && a.path.length === b.path.length) {
      const path = a.path.map((v, i) => lerp(v, b.path[i], t));
      return { ...base, path, pts: centreLine(path) };
    }
    const n = Math.max(a.pts.length, b.pts.length, 2), pts = [];
    for (let i = 0; i < n; i++) pts.push(lerp2(resample(a.pts, i, n), resample(b.pts, i, n), t));
    return { ...base, path: null, pts };
  }

  /** An eye seen as a straight stadium: centre, angle, half length, half width. */
  function stadiumOf(e) {
    if (isOval(e)) {
      const [rx, ry] = e.oval;
      return { cx: e.off[0], cy: e.off[1], ang: rx >= ry ? Math.PI / 2 : 0, halfLen: Math.max(rx, ry), halfW: Math.min(rx, ry) };
    }
    const w = e.wid;
    if (e.pts.length < 2) return { cx: e.off[0], cy: e.off[1], ang: e.tilt, halfLen: w, halfW: w };
    const a = e.pts[0], b = e.pts[e.pts.length - 1];
    return {
      cx: e.off[0] + (a[0] + b[0]) / 2, cy: e.off[1] + (a[1] + b[1]) / 2,
      ang: Math.atan2(b[0] - a[0], b[1] - a[1]) + e.tilt,
      halfLen: Math.hypot(b[0] - a[0], b[1] - a[1]) / 2 + w, halfW: w,
    };
  }
  function turnBetween(a, b) {
    let d = b.ang - a.ang;
    while (d > Math.PI / 2) d -= Math.PI;
    while (d < -Math.PI / 2) d += Math.PI;
    return d;
  }

  /** 48-point outline blending a stadium (mix 0) into an ellipse (mix 1). */
  function stadiumEllipseRing(halfLen, halfW, mix) {
    const flat = Math.max(0, halfLen - halfW), m = clamp(mix, 0, 1), out = [];
    for (let i = 0; i < 48; i++) {
      const a = (i / 48) * TAU, c = Math.cos(a), s = Math.sin(a);
      const ex = halfW * c, ey = halfLen * s;
      const side = halfW / Math.max(Math.abs(c), 1e-6);
      let r;
      if (side * Math.abs(s) <= flat + 1e-6 && Number.isFinite(side)) r = side;
      else {
        const k = (s >= 0 ? 1 : -1) * flat * s;
        r = k + Math.sqrt(Math.max(0, k * k - flat * flat + halfW * halfW));
      }
      out.push([r * c + (ex - r * c) * m, r * s + (ey - r * s) * m]);
    }
    return out;
  }

  const uprightCapsule = (w, h, tilt, off) => capsuleEye(Math.max(w, 1e-4), Math.max(h, w), 0, off, tilt);

  /** "oval" morph: into or out of an oval eye. */
  function morphOval(a, b, t) {
    if (t <= 1e-4) return plain(a);
    if (t >= 0.995) return plain(b);
    const s0 = stadiumOf(a), s1 = stadiumOf(b), turn = turnBetween(s0, s1);
    const intoOval = isOval(b);
    const k = intoOval ? 1 - (1 - t) ** 3 : t * t * t;
    const ang = s0.ang + turn * t;
    const halfLen = Math.max(lerp(s0.halfLen, s1.halfLen, t), 1e-4);
    const halfW = Math.max(lerp(s0.halfW, s1.halfW, t), 1e-4);
    const from = +isOval(a), mix = from + (+intoOval - from) * k;
    const eye = uprightCapsule(2 * halfW, 2 * halfLen, ang, [lerp(s0.cx, s1.cx, t), lerp(s0.cy, s1.cy, t)]);
    const on = mix > 1e-4;
    return { ...eye, oval: on ? [halfW, halfLen] : eye.oval, ovalMix: on ? mix : 0, fillRing: stadiumEllipseRing(halfLen, halfW, mix) };
  }

  /** "stadium" morph: lerp centre, angle, half length and half width. */
  function morphStadium(a, b, t) {
    if (t >= 0.9999) return plain(b);
    const s0 = stadiumOf(a), s1 = stadiumOf(b);
    const ang = s0.ang + turnBetween(s0, s1) * t;
    const halfW = Math.max(1e-4, lerp(s0.halfW, s1.halfW, t));
    const flat = Math.max(0, s0.halfLen - s0.halfW) * (1 - t) + Math.max(0, s1.halfLen - s1.halfW) * t;
    return capsuleEye(2 * halfW, 2 * (flat + halfW), ang / DEG, [lerp(s0.cx, s1.cx, t), lerp(s0.cy, s1.cy, t)], 0);
  }

  /** Bounding size of an eye after its tilt. */
  function eyeExtent(e) {
    let box = null;
    if (isOval(e)) box = { width: 2 * e.oval[0], height: 2 * e.oval[1] * e.lidY, tilt: e.tilt / DEG, cx: e.off[0], cy: e.off[1] };
    else if (e.wid > 0 && e.pts.length >= 2) {
      const a = e.pts[0], b = e.pts[e.pts.length - 1], dx = b[0] - a[0], dy = b[1] - a[1], w = 2 * e.wid;
      box = {
        width: w, height: (Math.hypot(dx, dy) + w) * e.lidY, tilt: Math.atan2(dx, dy) / DEG + e.tilt / DEG,
        cx: e.off[0] + (a[0] + b[0]) / 2, cy: e.off[1] + ((a[1] + b[1]) / 2) * e.lidY,
      };
    }
    if (!box) return { w: EYE_WIDTH, h: 0.57, cx: e.off[0], cy: e.off[1] };
    const t = box.tilt * DEG, c = Math.abs(Math.cos(t)), s = Math.abs(Math.sin(t));
    return { w: box.width * c + box.height * s, h: box.width * s + box.height * c, cx: box.cx, cy: box.cy };
  }

  /** Blink: the eye squashes into a horizontal pill w long and 0.42 w thick. */
  function blinkShape(e, amount) {
    if (amount <= 0) return e;
    const k = Math.min(1, amount), ext = eyeExtent(e);
    const w = Math.max(ext.w, 1e-4), h = Math.max(ext.h, w);
    const target = h + (w * 0.42 - h) * k;
    return target >= w
      ? uprightCapsule(w, target, 0, [ext.cx, ext.cy])
      : uprightCapsule(target, w, Math.PI / 2, [ext.cx, ext.cy]);
  }

  const hiddenEye = (e) => ({ ...e, wid: 0, oval: [0, 0] });

  /** Height (eye units) the lid closes toward: 40% up from the bottom. */
  function lidLine(e) {
    let lo, hi;
    if (isOval(e)) { lo = -e.oval[1]; hi = e.oval[1]; } else {
      lo = 1e9; hi = -1e9;
      for (const p of e.pts) { if (p[1] < lo) lo = p[1]; if (p[1] > hi) hi = p[1]; }
      lo -= e.wid; hi += e.wid;
    }
    return lo + 0.4 * (hi - lo);
  }
  /** Turn a mostly vertical centre line upright, moving its angle into `tilt`. */
  function upright(e) {
    if (e.pts.length < 2) return e;
    const a = e.pts[0], b = e.pts[e.pts.length - 1], dx = b[0] - a[0], dy = b[1] - a[1];
    if (Math.abs(dy) < Math.abs(dx)) return e;
    const ang = Math.atan2(dx, dy);
    if (Math.abs(ang) < 1e-5) return e;
    const c = Math.cos(ang), s = Math.sin(ang);
    return { ...e, tilt: e.tilt + ang, pts: e.pts.map((p) => [p[0] * c - p[1] * s, p[0] * s + p[1] * c]) };
  }
  /** Lid closing by `amount` (used when a face changes "through a blink"). */
  function lidClose(e, amount) {
    if (amount === 0) return e;
    const u = upright(e), open = Math.max(0.03, 1 - amount);
    const shift = lidLine(u) * (1 - open), c = Math.cos(-u.tilt), s = Math.sin(-u.tilt);
    return { ...u, off: [u.off[0] - s * shift, u.off[1] + c * shift], lidY: u.lidY * open };
  }

  /** "inspecting": one eye grows, the other shrinks (bias follows the head turn). */
  function inspectScale(pair, weight, settings, yawDeg) {
    if (weight < 0.001) return pair;
    const bias = settings.isFollowingTurn ? clamp(yawDeg / 20, -1, 1) : settings.bias;
    const [big, small] = EXPRESSIONS.inspecting;
    const wb = Math.max(1e-4, big.wid), ws = Math.max(1e-4, small.wid), p = (1 + bias) / 2;
    const scaled = (e, k) => {
      const r = 1 + (k - 1) * weight;
      return { ...plain(e), wid: e.wid * r, pts: e.pts.map((q) => [q[0] * r, q[1] * r]) };
    };
    return [scaled(pair[0], (ws / wb) ** p), scaled(pair[1], (wb / ws) ** p)];
  }

  /** Blink amount curve: smoothstep close, short hold, smoothstep open. */
  function blinkPhases(isBlink, dur) {
    const hold = Math.min(0.28, (isBlink ? 2 / 60 : 4.25 / 60) / Math.max(dur, 0.05));
    const close = (1 - hold) * 0.42;
    return { u1: close, u2: close + hold };
  }
  const blinkCurve = (u, { u1, u2 }) => (u < u1 ? smooth01(u / u1) : u <= u2 ? 1 : 1 - smooth01((u - u2) / Math.max(1e-6, 1 - u2)));
  /** Lid re-opening with a small overshoot. */
  function lidOpen(t) {
    const x = clamp(t, 0, 1);
    if (x < 0.7) { const e = x / 0.7; return (1 - (1 - e) * (1 - e)) * 1.06; }
    return 1.06 - 0.06 * smooth01((x - 0.7) / 0.3);
  }

  /** The face: current expression, expression morphs, lid morphs and blinks. */
  function createFace() {
    let name = 'neutral';
    let rest = pairMap(EXPRESSIONS.neutral, plain);
    let restInspect = 0;
    let act = null; // { kind: 'morph'|'lidMorph'|'blink', ... }
    const morphT = (a) => bezierEase(clamp(a.t / a.dur, 0, 1), EASE_FACE);
    const inspectOf = (n) => +(n === 'inspecting');

    const eyes = () => {
      if (act == null) return rest;
      if (act.kind === 'blink') return act.from;
      if (act.kind === 'morph') {
        const t = clamp(morphT(act), 0, 1);
        const f = act.path === 'oval' ? morphOval : act.path === 'spine' ? morphSpine : morphStadium;
        return pairMap(act.from, (e, i) => f(e, act.to[i], t));
      }
      const u = Math.min(act.t / act.dur, 1), { u1, u2 } = blinkPhases(false, act.dur);
      if (u < u1) return pairMap(act.from, (e) => lidClose(e, smooth01(u / u1)));
      if (u <= u2) return pairMap(act.to, hiddenEye);
      const open = lidOpen((u - u2) / Math.max(1e-6, 1 - u2));
      return pairMap(act.to, (e) => lidClose(e, 1 - open));
    };
    const inspectWeight = () => {
      if (act == null) return restInspect;
      if (act.kind === 'blink') return act.fromInspect;
      const a = act.fromInspect, b = inspectOf(act.toName);
      if (act.kind === 'morph') return a + (b - a) * morphT(act);
      const u = Math.min(act.t / act.dur, 1), { u1, u2 } = blinkPhases(false, act.dur);
      return u <= u1 ? a : u < u2 ? 0 : b;
    };
    const morph = (to) => {
      const from = pairMap(eyes(), plain), target = EXPRESSIONS[to];
      const spine = from.some(isCurved) || target.some(isCurved) || name === 'sleepy' || to === 'sleepy';
      const path = !(from.some(isCurved) || target.some(isCurved)) && (from.some(isOval) || target.some(isOval)) ? 'oval' : spine ? 'spine' : 'stadium';
      act = { kind: 'morph', path, fromInspect: inspectWeight(), toName: to, from, to: target, t: 0, dur: FACE_CHANGE_S, isHeld: false };
      name = to;
    };
    const lidMorph = (to) => {
      act = { kind: 'lidMorph', fromInspect: inspectWeight(), toName: to, from: pairMap(eyes(), plain), to: EXPRESSIONS[to], t: 0, dur: BRIDGE_S, isHeld: false };
      name = to;
    };
    const blink = () => {
      if (act == null || act.isHeld) {
        act = { kind: 'blink', fromInspect: restInspect, toName: name, from: pairMap(rest, plain), to: EXPRESSIONS[name], t: 0, dur: BLINK_S, isHeld: false };
      }
    };
    const play = (key) => {
      if (key.name !== name || (act != null && act.toName !== key.name)) {
        if (key.isThroughBlink && !LIDLESS.has(key.name) && !LIDLESS.has(name)) lidMorph(key.name); else morph(key.name);
      }
    };
    const setTime = (a, t) => {
      if (t >= a.dur) { rest = pairMap(a.to, plain); restInspect = inspectOf(a.toName); act = null; } else act = t < 0 ? null : { ...a, t };
    };
    return {
      get name() { return name; },
      get isMorphing() { return act != null && act.kind !== 'blink' && !act.isHeld; },
      eyes,
      inspectWeight,
      blinkAmount() {
        if (act == null || act.kind !== 'blink' || act.isHeld) return null;
        return clamp(blinkCurve(Math.min(act.t / act.dur, 1), blinkPhases(true, act.dur)), 0, 1);
      },
      morph, lidMorph, blink, play,
      step(dt) { if (act != null && !act.isHeld) setTime(act, act.t + dt); },
      release() { if (act != null) act = { ...act, isHeld: false }; },
      /** Jump to time `t` of an expression track; the result is held until release(). */
      seek(keys, t) {
        name = 'neutral'; rest = pairMap(EXPRESSIONS.neutral, plain); restInspect = 0; act = null;
        let last = 0;
        const run = (to) => { if (act != null) setTime(act, to - last); };
        for (const k of keys) {
          if (k.t > t + 1e-9) break;
          run(k.t); play(k); last = k.t;
        }
        run(t);
        if (act != null) act = { ...act, isHeld: true };
      },
    };
  }

