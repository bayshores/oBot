  const fitCache = new Map();
  /** Shrink the fill when the rest pose would poke outside the box. */
  function stillFill(body, fill) {
    const key = `${body}:${fill}`;
    if (fitCache.has(key)) return fitCache.get(key);
    const box = 1000 * fillScale(fill), c = box / 2;
    let reach = 0;
    for (const loop of canvasOutline(restFrame(body), body, box).body) for (const [x, y] of loop) reach = Math.max(reach, Math.abs(x - c), Math.abs(y - c));
    const out = reach <= 500 ? fill : (fill * 500) / reach;
    fitCache.set(key, out);
    return out;
  }

