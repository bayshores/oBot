  /** One requestAnimationFrame loop shared by every live avatar on the page. */
  const ticker = (() => {
    const jobs = new Set();
    let raf = 0;
    const loop = (now) => {
      raf = 0;
      for (const job of [...jobs]) if (!job(now)) jobs.delete(job);
      if (jobs.size > 0) raf = requestAnimationFrame(loop);
    };
    return {
      add(job) { jobs.add(job); if (!raf) raf = requestAnimationFrame(loop); },
      remove(job) { jobs.delete(job); if (jobs.size === 0 && raf) { cancelAnimationFrame(raf); raf = 0; } },
    };
  })();

