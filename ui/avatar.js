  const SPRITE_MIN = 144;            // geometry is computed at >= 144 units
  const SPRITE_RATIO = 184 / 256;    // the model is drawn ~1.39x the display size

  /** Largest power-of-two degree step that moves the rim by at most 0.6 px. */
  const angleStep = (box, zoom) => 2 ** Math.floor(Math.log2((0.6 / Math.max((box * zoom) / 2, 1)) / DEG));
  /** Keep yaw and pitch at least 0.5 degrees away from edge-on (90 mod 180). */
  function avoidEdgeOn(a) {
    const m = ((a % 180) + 180) % 180;
    return Math.abs(m - 90) >= 0.5 ? a : a + (m <= 90 ? 89.5 - m : 90.5 - m);
  }
  /** Frame orientation -> snapped yaw/pitch/roll in degrees. The face always turns toward the viewer. */
  function viewAngles(frame, box) {
    let m = quatMatrix(frame.quat);
    if (m[8] < 0) m = [-m[0], m[1], -m[2], -m[3], m[4], -m[5], -m[6], m[7], -m[8]];
    const step = angleStep(box, frame.zoom);
    const snap = (v) => (step > 0 ? Math.round(v / step) * step : v);
    const [p, y, r] = matrixEuler(m);
    return { yaw: avoidEdgeOn(snap(y / DEG)), pitch: avoidEdgeOn(snap(p / DEG)), roll: snap(r / DEG) };
  }

  // Body outline cache (LRU by total path length).
  const bodyPathCache = new Map();
  let bodyPathChars = 0;
  function bodyPaths(body, angles, sprite) {
    const sol = solid(body);
    const period = sol.silhouette.kind === 'solid' ? sol.silhouette.yawPeriod : null;
    const yaw = period == null ? angles.yaw : angles.yaw - period * Math.floor(angles.yaw / period);
    const key = `${body} ${sprite} ${yaw} ${angles.pitch} ${angles.roll}`;
    const hit = bodyPathCache.get(key);
    if (hit) { bodyPathCache.delete(key); bodyPathCache.set(key, hit); return hit; }
    const polys = silhouettePolys(sol, { yaw, pitch: angles.pitch, roll: angles.roll }, sprite);
    let paths;
    if (polys.length === 1) paths = [loopsPath(polys)];
    else { const d = polygonUnion(polys); paths = d === '' ? [] : [d]; }
    bodyPathCache.set(key, paths);
    bodyPathChars += paths.reduce((s, d) => s + d.length, 0);
    for (const [k, v] of bodyPathCache) {
      if (bodyPathChars <= 16e6) break;
      bodyPathCache.delete(k);
      bodyPathChars -= v.reduce((s, d) => s + d.length, 0);
    }
    return paths;
  }

  function eyePaths(body, angles, sprite, eyes) {
    const sol = solid(body);
    if (sol.seat == null || eyes == null) return [];
    return seatEyes(sol.seat, shapeFace(body, eyes), makeView(sol, angles, sprite)).flatMap(flatLoop).map((l) => loopsPath([l]));
  }

  /** Sprite geometry for a non-blob body: paths in sprite units + the matrix that places them. */
  function spriteGeometry(frame, body, box) {
    const i = Math.max(8, Math.round((box * frame.zoom) / SPRITE_RATIO));
    const sprite = Math.max(i, SPRITE_MIN);
    const angles = viewAngles(frame, box);
    const half = box / 2;
    const cx = half + frame.offset[0] * frame.zoom * half;
    const cy = half - frame.offset[1] * frame.zoom * half;
    const pivot = cy - frame.squashAnchor * frame.zoom * half;
    const [sx, sy] = frame.squash, k = i / sprite;
    return {
      sprite,
      matrix: [sx * k, sy * k, cx - (sx * i) / 2, pivot + sy * (cy - i / 2 - pivot)],
      body: bodyPaths(body, angles, sprite),
      eyes: frame.eyes == null ? [] : eyePaths(body, angles, sprite, frame.eyes),
    };
  }

  /** Blob: an ellipse with eyes mapped onto a sphere. Returns centre, radius, ellipse radii, eye loops (px). */
  function sphereGeometry(frame, box) {
    const R = (frame.zoom * box) / 2, [sx, sy] = frame.squash;
    const cx = box / 2 + R * frame.offset[0];
    const cy = box / 2 - R * (frame.squashAnchor * (1 - sy) + frame.offset[1]);
    const eyes = frame.eyes == null ? [] : sphereEyeLoops(frame.eyes, frame.quat).map((l) => l.map(([x, y]) => [cx + x * R, cy - y * R]));
    return { cx, cy, R: Math.abs(R), rx: Math.abs(R * sx), ry: Math.abs(R * sy), eyes };
  }

  const node = (tag, attrs, children = []) => ({ tag, attrs, children });
  const pointsPath = (pts) => (pts.length === 0 ? '' : `M${pts.map(([x, y]) => `${fmt2(x)} ${fmt2(y)}`).join('L')}Z`);
  const svgRoot = (size, id, extent, children) => node('svg', {
    xmlns: 'http://www.w3.org/2000/svg', id, width: extent, height: extent, viewBox: `0 0 ${size} ${size}`,
  }, children);

  function holesMask(id, size, eyeD) {
    return node('mask', { id: `${id}-holes`, maskUnits: 'userSpaceOnUse', x: 0, y: 0, width: size, height: size }, [
      node('rect', { width: size, height: size, fill: '#fff' }),
      ...eyeD.map((d) => node('path', { d, fill: '#000' })),
    ]);
  }

  function spriteTree(frame, ink, box, id, extent, eyeColor) {
    const g = spriteGeometry(frame, frame.bodies[0].body, box);
    const [a, d, e, f] = g.matrix, r6 = (v) => fmt(v, 6);
    const defs = [node('g', { id: `${id}-body` }, g.body.map((p) => node('path', { d: p })))];
    const inner = [];
    if (g.eyes.length > 0 && !eyeColor) {
      defs.push(holesMask(id, g.sprite, g.eyes));
      inner.push(node('use', { href: `#${id}-body`, fill: ink, mask: `url(#${id}-holes)` }));
    } else {
      inner.push(node('use', { href: `#${id}-body`, fill: ink }));
      if (g.eyes.length > 0) {
        defs.push(node('clipPath', { id: `${id}-inside` }, g.body.map((p) => node('path', { d: p }))));
        inner.push(node('g', { 'clip-path': `url(#${id}-inside)` }, g.eyes.map((p) => node('path', { d: p, fill: eyeColor }))));
      }
    }
    return svgRoot(box, id, extent, [node('defs', {}, defs), node('g', { transform: `matrix(${r6(a)} 0 0 ${r6(d)} ${r6(e)} ${r6(f)})` }, inner)]);
  }

  const ellipseD = (cx, cy, rx, ry) => `M${fmt2(cx - rx)} ${fmt2(cy)}A${fmt2(rx)} ${fmt2(ry)} 0 1 0 ${fmt2(cx + rx)} ${fmt2(cy)}A${fmt2(rx)} ${fmt2(ry)} 0 1 0 ${fmt2(cx - rx)} ${fmt2(cy)}Z`;

  function sphereTree(frame, ink, box, id, extent, eyeColor) {
    const g = sphereGeometry(frame, box);
    if (g.R === 0 || g.rx === 0 || g.ry === 0) return svgRoot(box, id, extent, []);
    const body = ellipseD(g.cx, g.cy, g.rx, g.ry), eyeD = g.eyes.map(pointsPath);
    if (eyeD.length === 0) return svgRoot(box, id, extent, [node('path', { d: body, fill: ink })]);
    if (eyeColor) {
      return svgRoot(box, id, extent, [
        node('defs', {}, [node('clipPath', { id: `${id}-inside` }, [node('path', { d: body })])]),
        node('path', { d: body, fill: ink }),
        node('g', { 'clip-path': `url(#${id}-inside)` }, eyeD.map((d) => node('path', { d, fill: eyeColor }))),
      ]);
    }
    return svgRoot(box, id, extent, [node('defs', {}, [holesMask(id, box, eyeD)]), node('path', { d: body, fill: ink, mask: `url(#${id}-holes)` })]);
  }

