  const POKES = ['spin', 'bounce', 'nod'];
  const pokeLength = ({ poke, turns }) => (poke === 'spin' ? 0.9 + 0.4 * (turns - 1) : poke === 'bounce' ? 0.62 : 0.5);
  const bump = (e, a, b) => (e <= a || e >= b ? 0 : Math.sin((Math.PI * (e - a)) / (b - a)) ** 2);
  function pokeOffsets(pokes) {
    let pitch = 0, yaw = 0, lift = 0, sx = 1, sy = 1;
    for (const p of pokes) {
      const e = Math.min(1, p.t / pokeLength(p));
      if (p.poke === 'spin') yaw += 180 * p.turns * (1 - Math.cos(Math.PI * e));
      else if (p.poke === 'nod') pitch += 16 * bump(e, 0, 1);
      else if (p.poke === 'bounce') {
        const squash = bump(e, 0, 0.18) + bump(e, 0.82, 1), stretch = bump(e, 0.18, 0.82);
        lift += 0.3 * Math.sin(Math.PI * clamp((e - 0.14) / 0.72, 0, 1));
        sx *= 1 + 0.08 * squash - 0.04 * stretch;
        sy *= 1 - 0.1 * squash + 0.06 * stretch;
      }
    }
    return { pitch, yaw, lift, squash: [sx, sy] };
  }

  /** Pose for a gaze direction (gx, gy in -1..1, +y up). */
  function gazePose(body, gx, gy) {
    const solidBody = body !== 'sphere', m = body === 'heartChubby' ? 0.6 : body === 'wedge' ? 0.55 : 1;
    return {
      rx: -(solidBody ? 19 : 14) * m * gy, ry: (solidBody ? 26 : 18) * m * gx,
      px: (solidBody ? 0.07 : 0.03) * gx, py: (solidBody ? 0.055 : 0.024) * gy,
    };
  }
