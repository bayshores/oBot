  /** A clip's "blink" key becomes three lid keys: open, shut, open. */
  const blinkKeys = (t) => [
    { t, v: [0], ease: EASE_DEFAULT },
    { t: t + BLINK_S * 0.45, v: [1], ease: EASE_DEFAULT },
    { t: t + BLINK_S, v: [0], ease: EASE_DEFAULT },
  ];

  const clipCache = new Map();
  function clip(name) {
    let c = clipCache.get(name);
    if (c) return c;
    const raw = CLIPS[name];
    if (!raw) throw new Error(`OBAvatar: no clip named ${name}`);
    const tracks = { position: [], rotation: [], squash: [], zoom: [], lids: [], expression: [] };
    const exprKeys = [];
    for (const [k, keys] of Object.entries(raw.k)) {
      const target = TRACK_ALIASES[k];
      if (!target) continue;
      if (target === 'expression') { exprKeys.push(...keys); continue; }
      tracks[target] = keys.map(([t, v, ease]) => ({ t, v: typeof v === 'string' ? [] : v, ease: Array.isArray(ease) && ease.length === 4 ? ease : EASE_DEFAULT }));
    }
    let blinks = false;
    for (const [t, v, , cut] of exprKeys) {
      if (v === 'blink') { blinks = true; tracks.lids.push(...blinkKeys(t)); } else {
        tracks.expression.push({ t, name: typeof v === 'string' ? expressionName(v) : 'neutral', isThroughBlink: cut === false });
      }
    }
    if (blinks) tracks.lids.sort((a, b) => a.t - b.t);
    const [bias, follow] = raw.i || [];
    c = {
      name, duration: raw.d, squashAnchor: raw.a || 0, restTime: raw.r || 0,
      inspect: { bias: Number.isFinite(bias) ? clamp(bias, -1, 1) : undefined, isFollowingTurn: follow == null ? undefined : follow },
      ...tracks,
    };
    clipCache.set(name, c);
    return c;
  }

  /** Value of a track at time t (holds the first/last key outside the keyed range). */
  function sampleTrack(keys, t) {
    if (keys.length === 0) return null;
    if (t <= keys[0].t) return keys[0].v;
    const last = keys[keys.length - 1];
    if (t >= last.t) return last.v;
    let i = 0;
    while (i < keys.length - 2 && keys[i + 1].t <= t) i++;
    const a = keys[i], b = keys[i + 1];
    const k = bezierEase((t - a.t) / Math.max(b.t - a.t, 1e-9), a.ease);
    return a.v.map((v, j) => v + (b.v[j] - v) * k);
  }

  /** The pose a clip starts from (used when bridging into it). */
  function clipStartPose(c) {
    const t = c.restTime;
    const rot = sampleTrack(c.rotation, t), pos = sampleTrack(c.position, t), scl = sampleTrack(c.squash, t);
    const zoom = sampleTrack(c.zoom, t), lids = sampleTrack(c.lids, t);
    let expr = 'neutral', seen = false;
    for (const k of c.expression) {
      if (!seen) { expr = k.name; seen = true; }
      if (k.t <= t + 1e-9) expr = k.name;
    }
    return {
      rot: rot ? [rot[0], rot[1], rot[2]] : [0, 0, 0], pos: pos ? [pos[0], pos[1]] : [0, 0], scl: scl ? [scl[0], scl[1]] : [1, 1],
      zoom: zoom ? zoom[0] : REST_ZOOM, lids: lids ? clamp(lids[0], 0, 1) : 0, expr, squashAnchor: c.squashAnchor,
    };
  }

  const nearestTurn = (to, from) => to + 360 * Math.round((from - to) / 360);
  const angleGap = (a, b) => Math.abs((((a - b) % 360) + 540) % 360 - 180);
  function posesMatch(a, b) {
    return angleGap(a.rot[0], b.rot[0]) < 4 && angleGap(a.rot[1], b.rot[1]) < 4 && angleGap(a.rot[2], b.rot[2]) < 4 &&
      Math.abs(a.pos[0] - b.pos[0]) < 0.015 && Math.abs(a.pos[1] - b.pos[1]) < 0.015 &&
      Math.abs(a.scl[0] - b.scl[0]) < 0.02 && Math.abs(a.scl[1] - b.scl[1]) < 0.02 &&
      Math.abs(a.zoom - b.zoom) < 0.02 && Math.abs(a.lids - b.lids) < 0.05;
  }
  /** A 0.35 s clip that blends from one pose to another (angles take the short way). */
  function bridgeClip(from, to) {
    const keys = (a, b) => [{ t: 0, v: a, ease: EASE_BRIDGE_IN }, { t: BRIDGE_S, v: b, ease: EASE_DEFAULT }];
    const rot = [nearestTurn(to.rot[0], from.rot[0]), nearestTurn(to.rot[1], from.rot[1]), nearestTurn(to.rot[2], from.rot[2])];
    return {
      ...EMPTY_CLIP, name: 'bridge', duration: BRIDGE_S, squashAnchor: from.squashAnchor,
      position: keys(from.pos, to.pos), rotation: keys(from.rot, rot), squash: keys(from.scl, to.scl),
      zoom: keys([from.zoom], [to.zoom]), lids: from.lids === 0 && to.lids === 0 ? [] : keys([from.lids], [to.lids]),
    };
  }

