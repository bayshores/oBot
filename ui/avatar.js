  /** Rebuild the teardrop outline with a different apex cut (the pencil core uses 18). */
  function teardropPath(cut) {
    const r = 88, apexY = L - 114, cy = L + 26;
    const i = clamp(r / (cy - apexY), -1, 1), a = Math.sqrt(1 - i * i);
    const right = [L + r * a, cy - r * i], left = [L - r * a, cy - r * i];
    const ang = Math.atan2(right[1] - cy, right[0] - L);
    return new PathBuilder().corner(right, [L, apexY], left, cut).line(left[0], left[1]).arc(L, cy, r, r, Math.PI - ang, ang).close();
  }

