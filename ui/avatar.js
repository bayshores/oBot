  const TAU_ANGLES_192 = Array.from({ length: 192 }, (_, i) => (i / 192) * TAU);
  const angleAround = (c, x, y) => { const a = Math.atan2(y - c[1], x - c[0]); return a < 0 ? a + TAU : a; };

  function parseLoops(d) {
    const out = [];
    for (const part of d.split('Z')) {
      const nums = part.replace('M', ' ').trim().split(/\s+/).filter((s) => s !== '').map(Number);
      if (nums.length < 6) continue;
      const loop = [];
      for (let i = 0; i + 1 < nums.length; i += 2) loop.push([nums[i], nums[i + 1]]);
      out.push(loop);
    }
    return out;
  }

  /** Body + eye loops of one body in canvas px. */
  function canvasOutline(frame, body, box) {
    if (body === 'sphere') {
      const g = sphereGeometry(frame, box);
      const pts = Array.from({ length: 192 }, (_, i) => {
        const a = (i / 192) * TAU, c = Math.cos(a), s = Math.sin(a);
        const r = g.rx === 0 || g.ry === 0 ? 0 : 1 / Math.hypot(c / g.rx, s / g.ry);
        return [g.cx + c * r, g.cy + s * r];
      });
      return { centre: [g.cx, g.cy], radius: g.R, body: [pts], eyes: g.eyes };
    }
    const g = spriteGeometry(frame, body, box);
    const [a, d, e, f] = g.matrix, place = ([x, y]) => [a * x + e, d * y + f];
    return {
      centre: [(a * g.sprite) / 2 + e, (d * g.sprite) / 2 + f],
      radius: (frame.zoom * box) / 2,
      body: g.body.flatMap((p) => parseLoops(p).map((l) => l.map(place))),
      eyes: g.eyes.flatMap((p) => parseLoops(p).map((l) => l.map(place))),
    };
  }

  /** Farthest outline crossing along each angle (gaps filled by interpolation). */
  function radialOutline(loops, c, angles) {
    const BUCKETS = 720, buckets = Array.from({ length: BUCKETS }, () => []);
    for (const loop of loops) {
      for (let i = 0; i < loop.length; i++) {
        const p = loop[i], q = loop[(i + 1) % loop.length];
        const a0 = angleAround(c, p[0], p[1]);
        let span = angleAround(c, q[0], q[1]) - a0;
        if (span > Math.PI) span -= TAU;
        if (span < -Math.PI) span += TAU;
        const lo = Math.floor(((span < 0 ? a0 + span : a0) / TAU) * BUCKETS) - 1;
        const hi = Math.floor(((span < 0 ? a0 : a0 + span) / TAU) * BUCKETS) + 1;
        for (let b = lo; b <= hi; b++) buckets[((b % BUCKETS) + BUCKETS) % BUCKETS].push([p, q]);
      }
    }
    const reach = angles.map((a) => {
      const dx = Math.cos(a), dy = Math.sin(a);
      let best = NaN;
      for (const [[px, py], [qx, qy]] of buckets[Math.floor((a / TAU) * BUCKETS) % BUCKETS]) {
        const ex = qx - px, ey = qy - py, den = dx * ey - dy * ex;
        if (Math.abs(den) < 1e-12) continue;
        const ox = px - c[0], oy = py - c[1];
        const t = (ox * ey - oy * ex) / den, u = (ox * dy - oy * dx) / den;
        if (t >= 0 && u >= -1e-9 && u <= 1.000000001 && !(t <= best)) best = t;
      }
      return best;
    });
    const n = reach.length, known = reach.flatMap((v, i) => (Number.isNaN(v) ? [] : [i]));
    const filled = known.length === 0 ? reach.map(() => 0) : reach.map((v, i) => {
      if (!Number.isNaN(v)) return v;
      const after = known.find((k) => k > i) ?? known[0] + n;
      const before = [...known].reverse().find((k) => k < i) ?? (known[known.length - 1] ?? 0) - n;
      const t = (i - before) / (after - before);
      return reach[(before + n) % n] * (1 - t) + reach[after % n] * t;
    });
    return angles.map((a, i) => [c[0] + Math.cos(a) * filled[i], c[1] + Math.sin(a) * filled[i]]);
  }

  /** Reach of a star-shaped ring at each angle (by interpolating its sorted samples). */
  function ringAtAngles(pts, c, angles) {
    const samples = pts.map(([x, y]) => ({ angle: angleAround(c, x, y), reach: Math.hypot(x - c[0], y - c[1]) })).sort((a, b) => a.angle - b.angle);
    const n = samples.length;
    return angles.map((a) => {
      let i = samples.findIndex((s) => s.angle >= a);
      if (i < 0) i = 0;
      const hi = samples[i], lo = samples[(i - 1 + n) % n], gap = (hi.angle - lo.angle + TAU) % TAU;
      const r = gap === 0 ? hi.reach : lo.reach + (hi.reach - lo.reach) * (((a - lo.angle + TAU) % TAU) / gap);
      return [c[0] + Math.cos(a) * r, c[1] + Math.sin(a) * r];
    });
  }

  /** Resample a closed loop to `n` points by arc length, starting at its rightmost crossing of the centre line. */
  function resampleLoop(loop, n) {
    let area = 0;
    for (let i = 0; i < loop.length; i++) { const [x0, y0] = loop[i], [x1, y1] = loop[(i + 1) % loop.length]; area += x0 * y1 - x1 * y0; }
    const pts = area < 0 ? [...loop].reverse() : loop;
    let cx = 0, cy = 0;
    for (const [x, y] of pts) { cx += x; cy += y; }
    cx /= pts.length; cy /= pts.length;
    let start = null;
    for (let i = 0; i < pts.length; i++) {
      const [ax, ay] = pts[i], [bx, by] = pts[(i + 1) % pts.length];
      if (ay === by || (ay - cy) * (by - cy) > 0) continue;
      const x = ax + ((cy - ay) / (by - ay)) * (bx - ax);
      if (x >= cx && (start == null || x > start.point[0])) start = { edge: i, point: [x, cy] };
    }
    const ordered = start == null ? pts : [start.point, ...pts.slice(start.edge + 1), ...pts.slice(0, start.edge + 1)];
    const dist = [0];
    for (let i = 0; i < ordered.length; i++) {
      const [x0, y0] = ordered[i], [x1, y1] = ordered[(i + 1) % ordered.length];
      dist.push(dist[i] + Math.hypot(x1 - x0, y1 - y0));
    }
    const total = dist[ordered.length] || 1;
    const out = [];
    let k = 0;
    for (let j = 0; j < n; j++) {
      const s = (j / n) * total;
      while (k < ordered.length - 1 && dist[k + 1] < s) k++;
      const [x0, y0] = ordered[k], [x1, y1] = ordered[(k + 1) % ordered.length];
      const seg = dist[k + 1] - dist[k], t = seg === 0 ? 0 : (s - dist[k]) / seg;
      out.push([x0 + (x1 - x0) * t, y0 + (y1 - y0) * t]);
    }
    return out;
  }

  /** Eyes while two bodies blend: pair eyes by nearest centre and blend their outlines. */
  function blendEyes(shapes) {
    const reach = (shapes[0] ? shapes[0].shape.radius : 0) * 0.6;
    const centreOf = (l) => { let x = 0, y = 0; for (const p of l) { x += p[0]; y += p[1]; } return [x / l.length, y / l.length]; };
    const groups = [];
    shapes.forEach(({ shape }, si) => {
      for (const loop of shape.eyes) {
        const c = centreOf(loop);
        let best = null, bestD = reach;
        for (const g of groups) {
          if (g.loops[si] != null) continue;
          const d = Math.hypot(g.anchor[0] - c[0], g.anchor[1] - c[1]);
          if (d < bestD) { best = g; bestD = d; }
        }
        if (best) { best.loops[si] = loop; continue; }
        const loops = shapes.map(() => null);
        loops[si] = loop;
        groups.push({ anchor: c, loops });
      }
    });
    return groups.map((g) => {
      const res = g.loops.map((l) => (l == null ? null : resampleLoop(l, 96)));
      let total = 0;
      const out = Array.from({ length: 96 }, () => [0, 0]);
      shapes.forEach(({ weight }, si) => {
        const pts = res[si] || Array.from({ length: 96 }, () => g.anchor);
        total += weight;
        for (let i = 0; i < 96; i++) { out[i][0] += pts[i][0] * weight; out[i][1] += pts[i][1] * weight; }
      });
      return out.map(([x, y]) => [x / total, y / total]);
    });
  }

  function partNode(p, ink) {
    const op = p.opacity < 1 ? { opacity: fmt(p.opacity, 3) } : {};
    switch (p.type) {
      case 'disc': return node('circle', { cx: fmt2(p.cx), cy: fmt2(p.cy), r: fmt2(p.r), fill: ink, ...op });
      case 'ring': {
        const circ = 2 * Math.PI * p.r;
        const arc = p.arc == null ? {} : { 'stroke-dasharray': `${fmt2(circ * p.arc.fraction)} ${fmt2(circ)}`, transform: `rotate(${fmt2(p.arc.startDeg)} ${fmt2(p.cx)} ${fmt2(p.cy)})` };
        return node('circle', { cx: fmt2(p.cx), cy: fmt2(p.cy), r: fmt2(p.r), fill: 'none', stroke: ink, 'stroke-width': fmt2(p.width), ...arc, ...op });
      }
      case 'shape': return node('path', { d: p.d, transform: p.transform, fill: ink, ...op });
      default: return node('path', { d: p.d, fill: 'none', stroke: ink, 'stroke-width': fmt2(p.width), 'stroke-linecap': 'round', 'stroke-linejoin': 'round', ...op });
    }
  }

  /** Outline-blend renderer: body morphs, the core of morph overlays and their parts. */
  function blendTree(frame, ink, box, id, extent, displaySize) {
    const shapes = frame.bodies.map(({ body, weight }) => ({ shape: canvasOutline(frame, body, box), weight })).sort((a, b) => b.weight - a.weight);
    const lead = shapes[0] ? shapes[0].shape : { centre: [box / 2, box / 2], radius: 0 };
    const centre = lead.centre, radius = lead.radius;
    const all = [...TAU_ANGLES_192];
    for (const { shape } of shapes) for (const l of shape.body) for (const [x, y] of l) all.push(angleAround(shape.centre, x, y));
    all.sort((a, b) => a - b);
    const angles = all.filter((a, i) => i === 0 || a - all[i - 1] > 1e-7);
    const totalW = shapes.reduce((s, x) => s + x.weight, 0) || 1;
    const outlines = shapes.map(({ shape, weight }) => ({ pts: radialOutline(shape.body, shape.centre, angles), weight }));
    let bodyPts = angles.map((_, i) => {
      let x = 0, y = 0;
      for (const o of outlines) { x += o.pts[i][0] * o.weight; y += o.pts[i][1] * o.weight; }
      return [x / totalW, y / totalW];
    });
    const overlay = frame.morph == null ? null : morphOverlay(frame.morph, displaySize);
    const markScale = (REST_ZOOM * box) / 2 / L;
    const round = overlay ? overlay.core.round : 0;
    if (overlay && round !== 0) {
      const k = radius / L;
      const core = ringAtAngles(overlay.core.ring.map(([x, y]) => [centre[0] + (x - L) * k, centre[1] + (y - L) * k]), centre, angles);
      bodyPts = bodyPts.map(([x, y], i) => [x + (core[i][0] - x) * round, y + (core[i][1] - y) * round]);
    }
    const eyes = shapes.length === 1 ? shapes[0].shape.eyes : blendEyes(shapes);
    const bodyD = pointsPath(bodyPts), eyeD = eyes.map(pointsPath).join('');
    const defs = [];
    let drawn = [node('path', { d: bodyD, fill: ink })];
    if (eyeD !== '') {
      defs.push(node('mask', { id: `${id}-holes`, maskUnits: 'userSpaceOnUse', x: 0, y: 0, width: box, height: box }, [
        node('rect', { width: box, height: box, fill: '#fff' }), node('path', { d: eyeD, fill: '#000' }),
      ]));
      drawn = [node('path', { d: bodyD, fill: ink, mask: `url(#${id}-holes)` })];
    }
    if (overlay) {
      const amt = frame.morph.amount, keep = 1 - amt, c = overlay.core;
      const grow = amt > 0 ? (c.scale - keep) / amt : 0;
      const scale = keep + (REST_ZOOM / frame.zoom) * grow * amt;
      drawn = [node('g', {
        transform: `translate(${fmt2(centre[0] + c.dx * markScale)} ${fmt2(centre[1] + c.dy * markScale)}) rotate(${fmt2(c.rotation)}) scale(${fmt(scale, 5)}) translate(${fmt2(-centre[0])} ${fmt2(-centre[1])})`,
        ...(c.opacity < 1 ? { opacity: fmt(c.opacity, 3) } : {}),
      }, drawn)];
    }
    const parts = overlay && overlay.parts.length > 0
      ? [node('g', { transform: `translate(${box / 2} ${box / 2}) scale(${fmt(markScale, 5)}) translate(${-L} ${-L})` }, overlay.parts.map((p) => partNode(p, ink)))]
      : [];
    const zoom = overlay ? overlay.zoom : 1, pivot = box / 2 + (OVERLAY_CENTRE - L) * markScale;
    const content = zoom === 1 ? [...parts, ...drawn]
      : [node('g', { transform: `translate(${fmt2(pivot)} ${fmt2(pivot)}) scale(${fmt(zoom, 5)}) translate(${fmt2(-pivot)} ${fmt2(-pivot)})` }, [...parts, ...drawn])];
    return svgRoot(box, id, extent, [...(defs.length ? [node('defs', {}, defs)] : []), ...content]);
  }

  /** Pick the renderer for a frame. */
  function frameTree(frame, ink, box, id, { extent = '100%', displaySize = box, eyeColor = null } = {}) {
    const [first, ...others] = frame.bodies;
    if (first == null || others.length > 0 || frame.morph != null) return blendTree(frame, ink, box, id, extent, displaySize);
    return first.body === 'sphere' ? sphereTree(frame, ink, box, id, extent, eyeColor) : spriteTree(frame, ink, box, id, extent, eyeColor);
  }

  const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };
  const SELF_CLOSING = new Set(['path', 'use', 'rect', 'stop', 'circle']);
  function markup(n) {
    let attrs = '';
    for (const [k, v] of Object.entries(n.attrs)) attrs += ` ${k}="${String(v).replace(/[&<>"]/g, (c) => ESCAPES[c])}"`;
    return SELF_CLOSING.has(n.tag) ? `<${n.tag}${attrs}/>` : `<${n.tag}${attrs}>${n.children.map(markup).join('')}</${n.tag}>`;
  }

  /** Write a tree into `host`; when only attribute values changed, patch them in place. */
  const patchState = new WeakMap();
  function patchInto(host, tree) {
    const names = [], values = [];
    const walk = (n) => {
      names.push(n.tag);
      for (const [k, v] of Object.entries(n.attrs)) { names.push(k); values.push(String(v)); }
      for (const c of n.children) walk(c);
      names.push('/');
    };
    walk(tree);
    const sig = names.join('|');
    const st = patchState.get(host);
    if (st && st.sig === sig && host.firstChild === st.root) {
      for (let i = 0; i < values.length; i++) if (values[i] !== st.values[i]) st.slots[i].value = values[i];
      st.values = values;
      return;
    }
    host.innerHTML = markup(tree);
    const root = host.firstChild;
    const slots = [root, ...root.querySelectorAll('*')].flatMap((el) => [...el.attributes]);
    patchState.set(host, { sig, root, slots, values });
  }

