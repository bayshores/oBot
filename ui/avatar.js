  /** Builds an SVG path string; every number is rounded to 2 decimals. */
  class PathBuilder {
    constructor() { this.d = ''; }
    move(x, y) { this.d += `M${round2(x)} ${round2(y)}`; return this; }
    line(x, y) { this.d += `L${round2(x)} ${round2(y)}`; return this; }
    curve(x1, y1, x2, y2, x, y) {
      this.d += `C${round2(x1)} ${round2(y1)} ${round2(x2)} ${round2(y2)} ${round2(x)} ${round2(y)}`;
      return this;
    }
    /** Rounded corner at `at`: step back `cut` along both edges, join with a quadratic curve. */
    corner(prev, at, next, cut) {
      const unit = (p) => {
        const dx = p[0] - at[0], dy = p[1] - at[1];
        const len = Math.hypot(dx, dy) || 1;
        return [dx / len, dy / len];
      };
      const a = unit(prev), b = unit(next);
      const start = [at[0] + a[0] * cut, at[1] + a[1] * cut];
      const end = [at[0] + b[0] * cut, at[1] + b[1] * cut];
      if (this.d) this.line(start[0], start[1]); else this.move(start[0], start[1]);
      this.d += `Q${round2(at[0])} ${round2(at[1])} ${round2(end[0])} ${round2(end[1])}`;
      return this;
    }
    /** Elliptical arc from angle `from` to `to`, as cubic pieces of at most 90 degrees. */
    arc(cx, cy, rx, ry, from, to) {
      const n = Math.max(1, Math.ceil(Math.abs(to - from) / (Math.PI / 2)));
      const step = (to - from) / n;
      const k = (4 / 3) * Math.tan(step / 4);
      let a0 = from;
      for (let i = 0; i < n; i++) {
        const a1 = a0 + step;
        const p0 = [cx + rx * Math.cos(a0), cy + ry * Math.sin(a0)];
        const p1 = [cx + rx * Math.cos(a1), cy + ry * Math.sin(a1)];
        this.curve(
          p0[0] - k * rx * Math.sin(a0), p0[1] + k * ry * Math.cos(a0),
          p1[0] + k * rx * Math.sin(a1), p1[1] - k * ry * Math.cos(a1),
          p1[0], p1[1],
        );
        a0 = a1;
      }
      return this;
    }
    close() { return this.d + 'Z'; }
  }

  /** Smooth closed curve through points (Catmull-Rom written as cubic Beziers). */
  function smoothClosed(pts) {
    const n = pts.length;
    let d = `M${round2(pts[0][0])} ${round2(pts[0][1])}`;
    for (let i = 0; i < n; i++) {
      const p0 = pts[(i - 1 + n) % n], p1 = pts[i], p2 = pts[(i + 1) % n], p3 = pts[(i + 2) % n];
      d += `C${round2(p1[0] + (p2[0] - p0[0]) / 6)} ${round2(p1[1] + (p2[1] - p0[1]) / 6)} ` +
        `${round2(p2[0] - (p3[0] - p1[0]) / 6)} ${round2(p2[1] - (p3[1] - p1[1]) / 6)} ` +
        `${round2(p2[0])} ${round2(p2[1])}`;
    }
    return d + 'Z';
  }

