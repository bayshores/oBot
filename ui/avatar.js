  /** Eye frames on the unit sphere: centre direction M, up T, outward C (left eye, right eye). */
  const SPHERE_EYES = [
    {
      M: [-0.3153457572898143, 0.000413547232064401, 0.948976755425548],
      T: [-0.0012276245071586862, 0.9999988905346685, -0.000843722407896131],
      C: [-0.948976051487804, -0.0014310514033447285, -0.31534489974391217],
    },
    {
      M: [0.3153457572898147, -0.000413547232064142, 0.948976755425548],
      T: [0.0012179979536934692, 0.9999992577584695, 0.000031040210269326975],
      C: [0.9489760638921817, -0.0011460633475971695, -0.31534602692677954],
    },
  ];

  /** One eye's outline in its own frame (before lid, tilt and offset). */
  function localEyeLoop(e) {
    if (e.fillRing != null && e.fillRing.length >= 3) return e.fillRing.map(([x, y]) => ({ x, y }));
    if (isOval(e)) {
      const out = [];
      for (let k = 0; k < 48; k++) { const a = (k / 48) * TAU; out.push({ x: e.oval[0] * Math.cos(a), y: e.oval[1] * Math.sin(a) }); }
      return out;
    }
    if (!(e.wid > 0)) return [];
    // The blob's eye is traced from its centre-line points (a distance field), not the Bezier path.
    return strokeFromPoints(e.pts.map((p) => ({ x: p[0], y: p[1] })), e.wid);
  }

  /**
   * Blob eye loops in unit-sphere screen space ([x, y], y up). The part of an eye
   * that turns behind the sphere is cut off along the visible rim.
   */
  function sphereEyeLoops(eyes, quat) {
    const m = quatMatrix(quat), out = [];
    eyes.forEach((e, i) => {
      const loop = localEyeLoop(e);
      if (loop.length < 3) return;
      const frame = SPHERE_EYES[i];
      const M = matVec(m, frame.M), C = matVec(m, frame.C), T = matVec(m, frame.T);
      const centreAngle = Math.atan2(M[1], M[0]);
      const ct = Math.cos(e.tilt), st = Math.sin(e.tilt), [ox, oy] = e.off;
      const pts = loop.map(({ x, y }) => {
        const ly = y * e.lidY;
        const u = ox + ct * x + st * ly, v = oy - st * x + ct * ly;
        const len = Math.sqrt(u * u + v * v), k = len > 1e-12 ? Math.sin(len) / len : 1, c = Math.cos(len);
        return [c * M[0] + k * (u * C[0] + v * T[0]), c * M[1] + k * (u * C[1] + v * T[1]), c * M[2] + k * (u * C[2] + v * T[2])];
      });
      const clipped = clipToFront(pts, centreAngle);
      if (clipped) out.push(clipped);
    });
    return out;
  }

  /** Keep the z > 0 part of a loop on the unit sphere; close cuts along the rim circle. */
  function clipToFront(pts, centreAngle) {
    const n = pts.length;
    let start = -1;
    for (let i = 0; i < n && start < 0; i++) if (pts[i][2] <= 0 && pts[(i + 1) % n][2] > 0) start = i;
    if (start < 0) return n === 0 || pts[0][2] <= 0 ? null : pts.map((p) => [p[0], p[1]]);
    const wrapAngle = (a) => a - TAU * Math.round(a / TAU);
    const cut = (p, q) => {
      const t = p[2] / (p[2] - q[2]), x = p[0] + (q[0] - p[0]) * t, y = p[1] + (q[1] - p[1]) * t, r = Math.hypot(x, y);
      return [x / r, y / r];
    };
    const rimArc = (from, to) => {
      const a0 = Math.atan2(from[1], from[0]);
      const sweep = wrapAngle(Math.atan2(to[1], to[0]) - centreAngle) - wrapAngle(a0 - centreAngle);
      const steps = Math.max(1, Math.ceil(Math.abs(sweep) / (Math.PI / 48))), arc = [];
      for (let k = 1; k <= steps; k++) { const a = a0 + (sweep * k) / steps; arc.push([Math.cos(a), Math.sin(a)]); }
      return arc;
    };
    const out = [];
    let entry = null, exit = null;
    for (let s = 0; s < n; s++) {
      const p = pts[(start + s) % n], q = pts[(start + s + 1) % n];
      const pIn = p[2] > 0, qIn = q[2] > 0;
      if (pIn && qIn) out.push([q[0], q[1]]);
      else if (pIn) { exit = cut(p, q); out.push(exit); } else if (qIn) {
        const enter = cut(p, q);
        if (exit === null) entry = enter; else out.push(...rimArc(exit, enter));
        out.push([q[0], q[1]]);
      }
    }
    if (exit !== null) out.push(...rimArc(exit, entry || [1, 0]));
    return out.length >= 3 ? out : null;
  }

