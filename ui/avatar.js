  const RING_POINTS = 64;
  const EXTRUDE_DEPTH = 0.36, EXTRUDE_BEVEL = 0.22, BEVEL_STEPS = 4;

  /** Width-of-outline-at-height lookup (64 buckets), in SVG units. */
  function widthLookup(pts) {
    const n = pts.length;
    let lo = Infinity, hi = -Infinity;
    for (const [, y] of pts) { if (y < lo) lo = y; if (y > hi) hi = y; }
    lo -= 1e-5; hi += 1e-5;
    const bucket = (y) => Math.min(63, Math.floor(((y - lo) / (hi - lo)) * 64));
    const buckets = Array.from({ length: 64 }, () => []);
    for (let i = 0; i < n; i++) {
      const a = pts[i][1], b = pts[(i + 1) % n][1];
      const end = bucket(Math.max(a, b) + 1e-5);
      for (let k = bucket(Math.min(a, b) - 1e-5); k <= end; k++) buckets[k].push(i);
    }
    return (y) => {
      let minX = Infinity, maxX = -Infinity;
      if (!(y >= lo && y <= hi)) return maxX - minX;
      for (const i of buckets[bucket(y)]) {
        const [ax, ay] = pts[i], [bx, by] = pts[(i + 1) % n];
        if (Math.abs(by - ay) < 1e-9) {
          if (Math.abs(ay - y) < 1e-6) { minX = Math.min(minX, ax, bx); maxX = Math.max(maxX, ax, bx); }
        } else if ((ay <= y && by >= y) || (by <= y && ay >= y)) {
          const x = ax + ((bx - ax) * (y - ay)) / (by - ay);
          if (x < minX) minX = x;
          if (x > maxX) maxX = x;
        }
      }
      return maxX - minX;
    };
  }

  /** Radius-at-height for a surface of revolution, in model units. */
  function radiusLookup(pts) {
    const width = widthLookup(pts);
    let lo = Infinity, hi = -Infinity;
    for (const [, y] of pts) { if (y < lo) lo = y; if (y > hi) hi = y; }
    return (ym) => Math.max(0.02, width(clamp(L - ym * L, lo, hi)) / 2 / L);
  }

  function ringAt(y, r) {
    const out = [];
    for (let i = 0; i < RING_POINTS; i++) {
      const a = (i / RING_POINTS) * TAU;
      out.push({ x: r * Math.sin(a), y, z: r * Math.cos(a) });
    }
    return out;
  }

  /** Surface of revolution: radius at each height = half the outline width there. */
  function revolvePoints(pts) {
    let top = Infinity, bottom = -Infinity;
    for (const [, y] of pts) { if (y < top) top = y; if (y > bottom) bottom = y; }
    const width = widthLookup(pts);
    const radius = (y) => { const w = width(y); return w < 0 ? 0 : w / 2 / L; };
    const h = bottom - top;
    const tip = (yEdge, sign) => {
      if (radius(yEdge) >= 0.06) return null;
      const r0 = radius(yEdge);
      let dJoin = h * 0.02;
      for (let d = h / 512; d <= h * 0.05; d += h / 512) {
        if (Math.abs(radius(yEdge + sign * d) - r0) > 1e-4) { dJoin = d; break; }
      }
      return { yEdge, sign, dJoin, rJoin: radius(yEdge + sign * dJoin) };
    };
    const tips = [tip(top, 1), tip(bottom, -1)].filter(Boolean);
    const rounded = (y) => {
      let r = radius(y);
      for (const t of tips) {
        const d = (y - t.yEdge) * t.sign;
        if (d >= 0 && d < t.dJoin) r = Math.min(r, t.rJoin * Math.sqrt(d / t.dJoin));
      }
      return r;
    };
    const out = [];
    const cap = (ym, ys) => {
      const r = rounded(ys);
      if (r < 0.06) out.push({ x: 0, y: ym, z: 0 }); else out.push(...ringAt(ym, r));
    };
    cap(-(top - L) / L, top);
    for (let e = 1; e < 95; e++) {
      const ys = top + h * ((1 - Math.cos((e / 95) * Math.PI)) / 2);
      const r = rounded(ys), ym = -(ys - L) / L;
      if (r < 1e-4) out.push({ x: 0, y: ym, z: 0 }); else out.push(...ringAt(ym, r));
    }
    cap(-(bottom - L) / L, bottom);
    return out;
  }

  function ringBox(name) {
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    for (const [x, y] of outline(name).ring) {
      if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
    }
    return { x0, x1, y0, y1 };
  }

  /** Pill: 33 equal balls along one axis. Each ball is [x, y, z, r]. */
  function pillBalls(name, axis) {
    const { x0, x1, y0, y1 } = ringBox(name);
    const hx = (x1 - x0) / 2 / L, hy = (y1 - y0) / 2 / L;
    const r = axis === 'x' ? hy : hx;
    const reach = Math.max(0, (axis === 'x' ? hx : hy) - r);
    const balls = [];
    for (let i = 0; i < 33; i++) {
      const c = -reach + 2 * reach * (i / 32);
      balls.push(axis === 'x' ? [c, 0, 0, r] : [0, c, 0, r]);
    }
    return balls;
  }

  /** Bean: union of the largest balls that fit inside the outline (greedy). */
  function inscribedBalls(name) {
    const pts = outlinePoints(name);
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    for (const [x, y] of pts) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
    const inside = (px, py) => {
      let hit = false;
      for (let a = 0, b = pts.length - 1; a < pts.length; b = a++) {
        const [ax, ay] = pts[a], [bx, by] = pts[b];
        if ((ay > py) !== (by > py) && px < ax + ((bx - ax) * (py - ay)) / (by - ay)) hit = !hit;
      }
      return hit;
    };
    const cell = Math.max(x1 - x0, y1 - y0) / 40;
    const found = [];
    for (let y = y0 + cell / 2; y < y1; y += cell) {
      for (let x = x0 + cell / 2; x < x1; x += cell) {
        if (!inside(x, y)) continue;
        let best = Infinity;
        for (const [px, py] of pts) best = Math.min(best, (px - x) ** 2 + (py - y) ** 2);
        const r = Math.sqrt(best);
        if (r > cell) found.push({ x, y, r });
      }
    }
    found.sort((a, b) => b.r - a.r);
    const kept = [];
    for (const b of found) {
      if (!kept.some((k) => Math.hypot(b.x - k.x, b.y - k.y) + b.r <= k.r + cell * 0.25)) kept.push(b);
    }
    return kept.map((b) => [(b.x - L) / L, -(b.y - L) / L, 0, b.r / L]);
  }

  /** Extrusion with a bevel approximated by shrinking copies (9 rings). */
  function extrusionRings(pts, halfDepth, bevel) {
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    for (const p of pts) { x0 = Math.min(x0, p.x); x1 = Math.max(x1, p.x); y0 = Math.min(y0, p.y); y1 = Math.max(y1, p.y); }
    const cx = (x0 + x1) / 2, cy = (y0 + y1) / 2;
    const l = Math.max(1e-4, Math.min((x1 - x0) / 2, (y1 - y0) / 2));
    const layer = (j, side) => {
      const th = (j / BEVEL_STEPS) * (Math.PI / 2);
      const z = halfDepth - bevel + bevel * Math.sin(th);
      return { z: side < 0 ? -z : z, scale: 1 - (bevel / l) * (1 - Math.cos(th)) };
    };
    const layers = [];
    for (let j = BEVEL_STEPS; j >= 0; j--) layers.push(layer(j, -1));
    for (let j = 0; j <= BEVEL_STEPS; j++) layers.push(layer(j, 1));
    return layers.map(({ z, scale }) => pts.map((p) => ({ x: cx + (p.x - cx) * scale, y: cy + (p.y - cy) * scale, z })));
  }

  function isConvex(pts) {
    let sign = 0;
    for (let i = 0; i < pts.length; i++) {
      const a = pts[i], b = pts[(i + 1) % pts.length], c = pts[(i + 2) % pts.length];
      const cross = (b.x - a.x) * (c.y - b.y) - (b.y - a.y) * (c.x - b.x);
      if (Math.abs(cross) < 1e-12) continue;
      if (sign === 0) sign = Math.sign(cross); else if (Math.sign(cross) !== sign) return false;
    }
    return true;
  }

  /** Squircle: the outline pushed inward along its normals, at 5 depths per side. */
  function roundedSlab(name, halfDepth, edge) {
    const ring = outline(name).ring.map(([x, y]) => ({ x: (x - L) / L, y: -(y - L) / L }));
    const n = ring.length, out = [];
    for (let i = 0; i < n; i++) {
      const p = ring[i], a = ring[(i - 1 + n) % n], b = ring[(i + 1) % n];
      let nx = b.y - a.y, ny = -(b.x - a.x);
      const len = Math.hypot(nx, ny) || 1;
      nx /= len; ny /= len;
      if (nx * p.x + ny * p.y < 0) { nx = -nx; ny = -ny; }
      for (let j = 0; j <= BEVEL_STEPS; j++) {
        const th = (j / BEVEL_STEPS) * (Math.PI / 2);
        const inset = edge * (1 - Math.cos(th));
        const z = halfDepth - edge + edge * Math.sin(th);
        out.push({ x: p.x - nx * inset, y: p.y - ny * inset, z });
        out.push({ x: p.x - nx * inset, y: p.y - ny * inset, z: -z });
      }
    }
    return out;
  }

  /** Crystal: 14 small balls (2 tips + two hexagonal rings), as a point cloud. */
  function crystalPoints() {
    const corners = [{ x: 0, y: 1.04, z: 0 }, { x: 0, y: -1.04, z: 0 }];
    for (const side of [-1, 1]) {
      for (let i = 0; i < 6; i++) {
        const a = (i / 6) * TAU;
        corners.push({ x: 0.52 * Math.cos(a), y: side * 0.51, z: 0.52 * Math.sin(a) });
      }
    }
    const r = 0.12, out = [];
    for (const c of corners) {
      for (let i = 0; i <= 8; i++) {
        const lat = (i / 8) * Math.PI, s = Math.sin(lat);
        const count = i === 0 || i === 8 ? 1 : 14;
        for (let j = 0; j < count; j++) {
          const lon = (j / count) * TAU;
          out.push({ x: c.x + r * s * Math.sin(lon), y: c.y + r * Math.cos(lat), z: c.z + r * s * Math.cos(lon) });
        }
      }
    }
    return out;
  }

  /** Flower: union of a centre circle and 6 petals, traced along 240 rays (model units). */
  function flowerPoints() {
    const discs = [{ x: 0, y: 0, r: 0.36 }];
    for (let i = 0; i < 6; i++) {
      const a = -Math.PI / 2 + (i * TAU) / 6;
      discs.push({ x: 0.58 * Math.cos(a), y: 0.58 * Math.sin(a), r: 0.33 });
    }
    const out = [];
    for (let i = 0; i < 240; i++) {
      const a = (i / 240) * TAU, c = Math.cos(a), s = Math.sin(a);
      let lo = 0, hi = 0.91;
      for (let k = 0; k < 22; k++) {
        const mid = (lo + hi) / 2, x = mid * c, y = mid * s;
        if (discs.some((d) => (x - d.x) ** 2 + (y - d.y) ** 2 <= d.r * d.r)) lo = mid; else hi = mid;
      }
      out.push({ x: lo * c, y: lo * s, z: 0 });
    }
    return out;
  }

  /** Loft (cloud, heart): 17 rings shrinking toward the edges, a puffy pillow ±depth thick. */
  function loft(pts, depth) {
    const stride = pts.length / 160;
    const src = stride > 1 ? Array.from({ length: 160 }, (_, i) => pts[Math.floor(i * stride)]) : pts;
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    for (const p of src) { x0 = Math.min(x0, p.x); x1 = Math.max(x1, p.x); y0 = Math.min(y0, p.y); y1 = Math.max(y1, p.y); }
    const centre = { x: (x0 + x1) / 2, y: (y0 + y1) / 2 };
    const rings = [];
    for (let e = 0; e <= 16; e++) {
      const th = -Math.PI / 2 + (Math.PI * e) / 16;
      const k = Math.max(0, Math.cos(th)) ** 0.72;
      const z = depth * Math.sin(th);
      rings.push(src.map((p) => ({ x: centre.x + (p.x - centre.x) * k, y: centre.y + (p.y - centre.y) * k, z })));
    }
    return { rings, centre, depth };
  }

  /** Height of the loft surface above the middle plane, z(x, y). */
  function loftSurface({ rings, centre, depth }) {
    const mid = rings[Math.floor(rings.length / 2)];
    const bins = 180, reach = new Float64Array(bins);
    for (let b = 0; b < bins; b++) {
      const a = ((b + 0.5) / bins) * TAU, c = Math.cos(a), s = Math.sin(a);
      let best = 0;
      for (let i = 0; i < mid.length; i++) {
        const p = mid[i], q = mid[(i + 1) % mid.length];
        const ex = q.x - p.x, ey = q.y - p.y;
        const den = c * ey - s * ex;
        if (Math.abs(den) < 1e-9) continue;
        const ox = p.x - centre.x, oy = p.y - centre.y;
        const dist = (ox * ey - oy * ex) / den, u = (ox * s - oy * c) / den;
        if (dist > best && u >= 0 && u <= 1) best = dist;
      }
      reach[b] = best;
    }
    const rho = (x, y) => {
      const dx = x - centre.x, dy = y - centre.y, d = Math.hypot(dx, dy);
      if (d < 1e-8) return 0;
      const f = (((Math.atan2(dy, dx) + TAU) % TAU) / TAU) * bins;
      const b = Math.floor(f) % bins, t = f - Math.floor(f);
      return Math.min(1, d / Math.max(1e-8, reach[b] * (1 - t) + reach[(b + 1) % bins] * t));
    };
    return (x, y) => depth * Math.sqrt(Math.max(0, 1 - rho(x, y) ** (2 / 0.72)));
  }

  /** Eye seat for revolve shapes: eyes wrap around the vertical axis. */
  function wrapSeat(name, balls) {
    const o = outline(name);
    const y0 = -(o.bottom - L) / L, y1 = -(o.top - L) / L;
    const radiusAt = radiusLookup(outlinePoints(name));
    const eyeY = Math.min(y1 - 0.02, Math.max(y0 + 0.02, 0));
    return {
      kind: 'wrap', wrapR: radiusAt(eyeY), wrapY0: y0, wrapY1: y1, eyeY, radiusAt,
      puffAt: balls.length > 0 ? (x, y) => ballUnder(balls, x, y) : undefined,
    };
  }

  /** The inscribed ball whose front surface is highest at (x, y). */
  function ballUnder(balls, x, y) {
    let pick = balls[0], top = -Infinity, gap = Infinity, covered = false;
    for (const b of balls) {
      const d = Math.hypot(x - b[0], y - b[1]);
      if (d < b[3]) {
        const z = b[2] + Math.sqrt(b[3] * b[3] - d * d);
        if (!covered || z > top) { covered = true; top = z; pick = b; }
      } else if (!covered && d - b[3] < gap) { gap = d - b[3]; pick = b; }
    }
    return { x: pick[0], y: pick[1], z: pick[2], r: pick[3] };
  }

