  /** Extra overlay parts of one morph kind, in L units (centre (L, L), y down). */
  function overlayParts(kind, amt, clk, coreR, reduced) {
    const ms = clk.stateTime * 1000;
    switch (kind) {
      case 'dots': {
        const xs = [L - 62, L + 62], out = [];
        for (let i = 0; i < 2; i++) {
          const t = clamp((amt - i * 0.12) / (1 - i * 0.12), 0, 1);
          if (t <= 0.004) continue;
          const grow = easeOutCubic(t), slide = easeOutBack(t), w = dotsWave(clk, i === 0 ? 0 : 2, amt, reduced);
          out.push(disc(`dots.${i}`, L + (xs[i] - L) * slide, L - w.lift, 22 * grow * w.pop * 1.02, grow * w.tone));
        }
        return out;
      }
      case 'orbit': {
        const grow = easeOutCubic(amt), r = 52 * easeOutBack(amt), base = ms * 0.0017;
        return Array.from({ length: 5 }, (_, i) => {
          const a = base + (i * TAU) / 5, c = Math.cos(a), size = 0.5 + 0.5 * clamp(c, 0, 1);
          return disc(`orbit.${i}`, L + r * Math.sin(a), L - r * 0.42 * c, Math.max(12 * size * grow, 0.3), clamp((c + 0.4) / 0.6, 0.18, 1) * grow);
        });
      }
      case 'radar': {
        const grow = easeOutCubic(amt);
        return Array.from({ length: 3 }, (_, i) => {
          const u = frac(ms / 1300 + i / 3);
          return ring(`radar.${i}`, coreR + (104 - coreR) * u, 3.4 * (1 - u * 0.55), grow * (1 - u) * 0.9);
        });
      }
      case 'progress': {
        const grow = easeOutCubic(amt), r = 62 * easeOutBack(amt);
        const fill = clamp(clamp((clk.shotTime * 1000) / (CYCLING_MORPHS.progress * 1000), 0, 1) / 0.85, 0, 1);
        const track = ring('progress.track', r, 5, grow * 0.16);
        return fill <= 0 ? [track] : [track, { type: 'ring', key: 'progress.arc', cx: L, cy: L, r, width: 5, opacity: grow, arc: { fraction: fill, startDeg: -90 } }];
      }
      case 'gather': {
        const grow = easeOutCubic(amt), out = [];
        for (let i = 0; i < 5; i++) {
          const u = clamp(((clk.shotTime * 1000) / (CYCLING_MORPHS.spawning * 1000) - i * 0.09) / 0.62, 0, 1);
          if (u >= 1) continue;
          const e = 1 - (1 - u) ** 3, a = i * 2.4 + u * 2.2, r = 96 * (1 - e);
          out.push(disc(`gather.${i}`, L + r * Math.cos(a), L + r * Math.sin(a) * 0.8, 9 * (0.5 + 0.5 * e) * grow, grow * clamp(u * 5, 0, 1) * (1 - e * 0.25)));
        }
        return out;
      }
      case 'wave': {
        const out = [];
        for (const i of [-2, -1, 1, 2]) {
          const t = clamp((amt - Math.abs(i) * 0.1) / (1 - Math.abs(i) * 0.1), 0, 1);
          if (t <= 0.004) continue;
          const level = meterAt(ms, i);
          out.push(disc(`wave.${i}`, L + i * 44 * easeOutBack(t), L - 6 * clamp(level, 0, 1) * t, (7 + 9 * clamp(level, 0.08, 1)) * easeOutCubic(t), t));
        }
        return out;
      }
      case 'send': {
        const grow = easeOutCubic(amt), u = frac(ms / SEND_PERIOD), dx = 0.74, dy = -0.62, out = [];
        const fly = clamp((u - 0.18) / 0.55, 0, 1), e = fly * fly * (0.4 + 0.6 * fly);
        if (fly > 0 && fly < 1) out.push(disc('send.packet', L + dx * 108 * e, L + dy * 108 * e, 10 * (1 - e * 0.55) * grow, grow * (1 - e * e)));
        const lag = clamp((u - 0.26) / 0.55, 0, 1), e2 = lag * lag * (0.4 + 0.6 * lag);
        if (fly > 0 && lag > 0 && lag < 1) out.push(disc('send.streak', L + dx * 108 * e2, L + dy * 108 * e2, 5 * (1 - e2 * 0.6) * grow, grow * 0.3 * (1 - e2)));
        const launch = clamp((u - 0.18) / 0.3, 0, 1);
        if (launch > 0 && launch < 1) out.push(ring('send.launch', 20 + 34 * easeOutCubic(launch), 2.8 * (1 - launch), grow * (1 - launch) * 0.8));
        return out;
      }
      case 'receive': {
        const grow = easeOutCubic(amt), from = -Math.PI * 1.25 + mulberry32(Math.floor(ms / RECEIVE_PERIOD))() * Math.PI * 1.5;
        const u = frac(ms / RECEIVE_PERIOD), t = clamp(u / 0.6, 0, 1), e = 1 - (1 - t) ** 3;
        const c = Math.cos(from), s = Math.sin(from), r = 108 * (1 - e), out = [];
        if (t < 1) {
          const bend = 18 * Math.sin(t * Math.PI) * (1 - e * 0.7);
          out.push(disc('receive.packet', L + c * r - s * bend, L + s * r + c * bend, 3.5 + 6.5 * e, grow * clamp(t * 3.5, 0, 1) * (0.3 + 0.7 * e)));
        }
        const absorb = clamp((u - 0.58) / 0.32, 0, 1);
        if (absorb > 0 && absorb < 1) out.push(ring('receive.absorb', 20 + 26 * easeOutCubic(absorb), 2.8 * (1 - absorb), grow * (1 - absorb) * 0.8));
        return out;
      }
      case 'dock': {
        const grow = easeOutCubic(amt), out = [];
        for (let i = 0; i < 2; i++) {
          const u = clamp((clk.stateTime - (0.2 + i * 1.3)) / 0.9, 0, 1);
          if (u <= 0) continue;
          const e = 1 - (1 - u) ** 3, a = ms * 0.001 * 1.1 + i * Math.PI;
          const ox = L + 42 * Math.sin(a), oy = L + 21 * Math.cos(a) + Math.sin(ms * 0.003 + i) * 2, sx = L - 120 + i * 30, sy = L + 95;
          out.push(disc(`dock.${i}`, sx + (ox - sx) * e, sy + (oy - sy) * e, (7 + 3 * e) * grow, grow * clamp(u * 4, 0, 1)));
        }
        return out;
      }
      case 'ball': return [];
      case 'pencil': {
        const p = pencilAt(ms), a = ((p.rot - 90) * Math.PI) / 180, ox = Math.cos(a) * 68, oy = Math.sin(a) * 68;
        const x = L + (p.x + ox) * amt, y = L + (p.y + p.wig * 0.15 + oy) * amt;
        const out = [{
          type: 'shape', key: 'pencil.shaft', d: PENCIL_SHAFT,
          transform: `translate(${x.toFixed(1)} ${y.toFixed(1)}) rotate(${(p.rot * amt).toFixed(1)}) scale(${easeOutCubic(amt).toFixed(3)}) translate(${-L} ${-L})`,
          opacity: clamp(amt * 1.6 - 0.3, 0, 1),
        }];
        const trail = pencilTrail(ms);
        if (trail.length >= 2) out.push({ type: 'stroke', key: 'pencil.ink', d: smoothOpenPath(trail), width: 6, opacity: clamp(amt * 1.2, 0, 1) });
        return out;
      }
      case 'bang': {
        const t = clk.stateTime, rise = easeOutCubic(clamp(amt * 1.1, 0, 1)), shake = Math.sin(t * 42) * 2.2 * Math.exp(-(t % 2.2) * 5.5);
        return [{
          type: 'shape', key: 'bang.bar', d: BANG_BAR,
          transform: `translate(0 ${(-26 - (1 - rise) * 70).toFixed(1)}) rotate(${shake.toFixed(2)} ${L} ${(L - 74).toFixed(1)}) translate(${L} ${L}) scale(${clamp(amt * 1.2, 0, 1).toFixed(3)}) translate(${-L} ${-L})`,
          opacity: clamp(amt * 1.5 - 0.2, 0, 1),
        }];
      }
      case 'standby': {
        const breath = 0.5 + 0.5 * Math.sin(ms * 0.0016);
        return [disc('standby.halo', L, L, 26 + 7 * breath, easeOutCubic(amt) * (0.06 + 0.1 * breath))];
      }
      default: return [];
    }
  }

  /** Core transform + parts for a morph snapshot (displaySize drives the small-size zoom). */
  function morphOverlay(m, displaySize) {
    const kind = m.kind, reduced = m.isReducedMotion;
    const amt = clamp(m.amount, 0, 1), sw = clamp(m.swap, 0, 1), out = sw < 0.999 ? m.outgoing : null;
    const weight = (k) => (k === kind ? amt * sw : k === out ? amt * (1 - sw) : 0);
    const clockOf = (k) => (k === kind ? m.clock : m.outgoingClock);
    const roundT = clamp(amt / 0.62, 0, 1);
    const shapeRing = kind !== 'pencil' && out !== 'pencil' ? circleRing
      : sw >= 0.999 ? coreRing(kind) : coreRing(out).map(([x, y], i) => { const b = coreRing(kind)[i]; const t = easeInOutCubic(sw); return [x + (b[0] - x) * t, y + (b[1] - y) * t]; });
    const coreR = kind ? CORE_RADIUS[kind] * sw + (out ? CORE_RADIUS[out] : CORE_RADIUS[kind]) * (1 - sw) : 19;
    const dotsW = weight('dots'), hasDots = kind === 'dots' || out === 'dots';
    const wave = hasDots ? dotsWave(clockOf('dots'), 1, amt, reduced) : { lift: 0, pop: 1, tone: 1 };
    let pulse = hasDots ? 1 + (wave.pop - 1) * (dotsW / Math.max(amt, 0.001)) : 1;
    const recvW = weight('receive');
    if (recvW > 0.004) {
      const u = clamp((frac((clockOf('receive').stateTime * 1000) / RECEIVE_PERIOD) - 0.58) / 0.34, 0, 1);
      pulse *= 1 + 0.11 * Math.sin(u * Math.PI) * recvW;
    }
    const sendW = weight('send');
    if (sendW > 0.004) {
      const u = frac((clockOf('send').stateTime * 1000) / SEND_PERIOD);
      const a = u < 0.18 ? -0.06 * Math.sin((u / 0.18) * Math.PI) : 0, b = u >= 0.18 && u < 0.42 ? 0.05 * Math.sin(((u - 0.18) / 0.24) * Math.PI) : 0;
      pulse *= 1 + (a + b) * sendW;
    }
    const bangW = weight('bang');
    if (bangW > 0.004) pulse *= 1 + 0.04 * Math.exp(-(clockOf('bang').stateTime % 2.2) * 5.5) * bangW;
    let dx = 0, dy = 0, turn = 0;
    const penW = weight('pencil');
    if (penW > 0.004) { const p = pencilAt(clockOf('pencil').stateTime * 1000); dx += p.x * penW; dy += (p.y + p.wig * 0.5) * penW; turn += p.rot * penW; }
    if (bangW > 0.004) dy += 58 * bangW;
    const ballW = weight('ball');
    if (ballW > 0.004) dy += ballHeight(clockOf('ball').stateTime) * ballW;
    const scale = (coreR / L) * pulse, standW = weight('standby');
    const dim = standW > 0 ? (0.28 + 0.2 * Math.sin(clockOf('standby').stateTime * 1000 * 0.0016)) * standW : 0;
    const fade = 1 - smoothRaw(clamp((displaySize - 44) / 90, 0, 1));
    const zIn = kind == null ? 1 : SMALL_ZOOM[kind], zOut = out ? SMALL_ZOOM[out] : zIn;
    const parts = [];
    for (const k of [out, kind]) {
      if (k == null) continue;
      const w = weight(k);
      if (w > 0.004) parts.push(...overlayParts(k, w, clockOf(k), coreR, reduced));
    }
    return {
      core: {
        scale: 1 - amt + scale * amt, dx: dx * amt, dy: -wave.lift * dotsW + dy * amt, rotation: turn * amt,
        opacity: (1 - (1 - wave.tone) * dotsW) * (1 - dim), round: easeInOutCubic(roundT), ring: shapeRing,
      },
      zoom: 1 + (zIn * sw + zOut * (1 - sw) - 1) * amt * fade,
      parts: parts.filter((p) => p.opacity > 0),
    };
  }

